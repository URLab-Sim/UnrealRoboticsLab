void CollectNames(const USceneComponent* Node,
	const std::vector<ElementType>& Targets, TArray<FString>& Out)
{
	if (Node == nullptr) return;
	if (const UMjNodeComponent* Doc = Cast<UMjNodeComponent>(Node))
	{
		ElementType Type;
		if (Doc->MjName.IsSet() && ElementTypeOfNode(*Doc, Type))
		{
			for (ElementType Want : Targets)
			{
				if (Want == Type) { Out.AddUnique(Doc->MjName.GetValue()); break; }
			}
		}
	}
	for (const USceneComponent* Child : Node->GetAttachChildren())
		CollectNames(Child, Targets, Out);
}


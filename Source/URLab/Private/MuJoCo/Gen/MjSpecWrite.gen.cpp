{
	const auto Utf8 = StringCast<UTF8CHAR>(*Value);
	const std::size_t Count = FMath::Min<std::size_t>(Utf8.Length(), N);
	std::memset(Dest, 0, N);
	std::memcpy(Dest, Utf8.Get(), Count);
}


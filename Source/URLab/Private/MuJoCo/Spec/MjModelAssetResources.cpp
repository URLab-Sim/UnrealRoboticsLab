bool MjBuildChildModelResources(const UMjModelAsset& ModelAsset,
	TArray<FMjPreparedAssetResource>& OutResources, FString& OutError)
{
	OutResources.Reset();
	OutError.Reset();
#if URLAB_MJ_GEN && WITH_EDITOR
	FBuildContext Context;
	if (!BuildOne(ModelAsset, Context, OutResources, OutError))
	{
		OutResources.Reset();
		return false;
	}
	if (OutResources.IsEmpty() || OutResources[0].Attribute != TEXT("file"))
	{
		OutError = TEXT("child model compiler payload is missing its model XML row");
		OutResources.Reset();
		return false;
	}
	return true;
#else
	(void)ModelAsset;
	OutError = TEXT("child model resources can only be generated in the editor");
	return false;
#endif
}

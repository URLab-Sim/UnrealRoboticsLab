FString StableId(const FString& Identity)
{
	FTCHARToUTF8 Utf8(*Identity);
	return FSHA1::HashBuffer(Utf8.Get(), Utf8.Length()).ToString().Left(16).ToLower();
}

FString SafeStem(const FString& Name)
{
	FString Stem = Name;
	for (TCHAR& Character : Stem)
	{
		if (!FChar::IsAlnum(Character) && Character != TEXT('_') && Character != TEXT('-'))
		{
			Character = TEXT('_');
		}
	}
	return Stem.IsEmpty() ? TEXT("model") : Stem;
}

FString ClassIdentity(const UClass& Class)
{
	return FSoftClassPath(&Class).ToString();
}

FString ModelKey(const UClass& Class)
{
	return FString::Printf(TEXT("__urlab_models/%s_%s"),
		*SafeStem(Class.GetName()), *StableId(ClassIdentity(Class)));
}

FString ScopedResourceName(const FString& ModelKeyName, const FString& File, const uint64 Serial)
{
	const FString Extension = FPaths::GetExtension(File, true);
	const FString Stem = SafeStem(FPaths::GetBaseFilename(File));
	return FString::Printf(TEXT("%s/assets/%s_%llu%s"), *ModelKeyName, *Stem, Serial, *Extension);
}

bool AppendUnique(TArray<FMjPreparedAssetResource>& Rows,
	const FMjPreparedAssetResource& Row, FString& OutError)
{
	for (const FMjPreparedAssetResource& Existing : Rows)
	{
		if (Existing.VfsName != Row.VfsName) continue;
		if (Existing.Bytes == Row.Bytes) return true;
		OutError = FString::Printf(TEXT("two generated child resources collide at VFS name '%s'"), *Row.VfsName);
		return false;
	}
	Rows.Add(Row);
	return true;
}

struct FBuildContext
{
	TSet<FString> ActiveClasses;
	TArray<FString> Chain;
};

bool BuildOne(const UMjModelAsset& ParentAsset, FBuildContext& Context,
	TArray<FMjPreparedAssetResource>& OutRows, FString& OutError)
{
	OutRows.Reset();
	UClass* ChildClass = ParentAsset.ChildModelClass.LoadSynchronous();
	if (ChildClass == nullptr || !ChildClass->IsChildOf(AMjArticulation::StaticClass()))
	{
		OutError = FString::Printf(TEXT("<model name='%s'> has no valid child articulation Blueprint"),
			*ParentAsset.MjName.Get(FString(TEXT("<unnamed>"))));
		return false;
	}
	const FString Identity = ClassIdentity(*ChildClass);
	if (Context.ActiveClasses.Contains(Identity))
	{
		TArray<FString> Cycle = Context.Chain;
		Cycle.Add(Identity);
		OutError = FString::Printf(TEXT("child model Blueprint cycle: %s"), *FString::Join(Cycle, TEXT(" -> ")));
		return false;
	}
	UBlueprint* ChildBlueprint = Cast<UBlueprint>(ChildClass->ClassGeneratedBy);
	if (ChildBlueprint == nullptr)
	{
		OutError = FString::Printf(TEXT("child model class '%s' is not generated by an editable Blueprint"), *Identity);
		return false;
	}
	const FSpecRef ChildSpec = FSpecRef::OverBlueprint(*ChildBlueprint);
	if (!ChildSpec.IsValid())
	{
		OutError = FString::Printf(TEXT("child model Blueprint '%s' has no authored MJCF spec"), *Identity);
		return false;
	}

	Context.ActiveClasses.Add(Identity);
	Context.Chain.Add(Identity);
	const FString ChildKey = ModelKey(*ChildClass);
	const FString ChildXmlFile = ChildKey + TEXT("/model.xml");
	TArray<FMjPreparedAssetResource> Dependencies;
	TArray<FMjXmlAttributeOverride> Overrides;
	const urlab::spec::FMjSpecNodes Nodes = urlab::spec::MjSpecNodesOf(ChildSpec);
	for (UMjNodeComponent* Node : Nodes.Nodes)
	{
		if (Node == nullptr) continue;
		if (UMjModelAsset* NestedModel = Cast<UMjModelAsset>(Node))
		{
			TArray<FMjPreparedAssetResource> NestedRows;
			if (!BuildOne(*NestedModel, Context, NestedRows, OutError))
			{
				Context.Chain.Pop();
				Context.ActiveClasses.Remove(Identity);
				return false;
			}
			if (NestedRows.IsEmpty())
			{
				OutError = TEXT("nested child model generated no compiler payload");
				Context.Chain.Pop();
				Context.ActiveClasses.Remove(Identity);
				return false;
			}
			const FMjPreparedAssetResource& NestedXml = NestedRows[0];
			Overrides.Add({Node->Serial, "file", NestedXml.VfsName});
			for (int32 Index = 0; Index < NestedRows.Num(); ++Index)
			{
				FMjPreparedAssetResource Dependency = NestedRows[Index];
				Dependency.Attribute.Reset();
				if (!AppendUnique(Dependencies, Dependency, OutError))
				{
					Context.Chain.Pop();
					Context.ActiveClasses.Remove(Identity);
					return false;
				}
			}
			continue;
		}

		ps::mjcf::ElementType Type{};
		if (!ps::ue::ElementTypeOfNode(*Node, Type)) continue;
		const ps::ue::FMjElementThunks& Fields = ps::ue::Thunks(Type);
		for (int32 FieldId = 0; FieldId < Fields.FieldCount; ++FieldId)
		{
			const ps::ue::FMjFieldSpec& Field = Fields.Fields[FieldId];
			if (!Field.bFileResource || !Fields.Has(Node, FieldId)) continue;
			FString AuthoredFile;
			if (!Fields.Format(Node, FieldId, AuthoredFile) || AuthoredFile.IsEmpty()) continue;

			if (Cast<UMjMesh>(Node) != nullptr || Cast<UMjTexture>(Node) != nullptr ||
				Cast<UMjFlexcomp>(Node) != nullptr)
			{
				FString PrepareError;
				if (!MjPrepareAssetResource(*Node, PrepareError))
				{
					OutError = FString::Printf(TEXT("child model '%s' could not prepare '%s': %s"),
						*Identity, *AuthoredFile, *PrepareError);
					Context.Chain.Pop();
					Context.ActiveClasses.Remove(Identity);
					return false;
				}
			}
			FString PreparedFile = AuthoredFile;
			Fields.Format(Node, FieldId, PreparedFile);

			const FMjPreparedAssetResource* SourceRow = nullptr;
			for (const FMjPreparedAssetResource& Candidate : Node->PreparedAssetResources)
			{
				if (Candidate.Attribute == FString(Field.XmlName) &&
					(Candidate.File == PreparedFile || Candidate.Attribute == TEXT("")) &&
					!Candidate.Bytes.IsEmpty())
				{
					SourceRow = &Candidate;
					break;
				}
			}
			if (SourceRow == nullptr)
			{
				OutError = FString::Printf(TEXT("child model '%s' has file resource '%s' on line %d without generated UE compiler bytes"),
					*Identity, *AuthoredFile, Node->SourceLine);
				Context.Chain.Pop();
				Context.ActiveClasses.Remove(Identity);
				return false;
			}
			FMjPreparedAssetResource Dependency = *SourceRow;
			Dependency.Attribute.Reset();
			Dependency.VfsName = ScopedResourceName(ChildKey, AuthoredFile, Node->Serial);
			Dependency.File = Dependency.VfsName;
			Overrides.Add({Node->Serial, Field.XmlName, Dependency.VfsName});
			if (!AppendUnique(Dependencies, Dependency, OutError))
			{
				Context.Chain.Pop();
				Context.ActiveClasses.Remove(Identity);
				return false;
			}
		}
	}

	TArray<FMjSpecDiagnostic> WriteDiagnostics;
	const FString Xml = ChildSpec.WriteMjcf(&WriteDiagnostics, &Overrides);
	if (Xml.IsEmpty())
	{
		OutError = WriteDiagnostics.IsEmpty() ? FString::Printf(TEXT("child model '%s' could not be serialized"), *Identity)
			: WriteDiagnostics[0].ToString();
		Context.Chain.Pop();
		Context.ActiveClasses.Remove(Identity);
		return false;
	}
	FTCHARToUTF8 XmlUtf8(*Xml);
	FMjPreparedAssetResource XmlRow;
	XmlRow.Attribute = TEXT("file");
	XmlRow.File = ChildXmlFile;
	XmlRow.VfsName = ChildXmlFile;
	XmlRow.AssetPath = FSoftObjectPath(ChildClass);
	XmlRow.Fingerprint = StableId(Xml + Identity);
	XmlRow.Bytes.Append(reinterpret_cast<const uint8*>(XmlUtf8.Get()), XmlUtf8.Length());
	OutRows.Add(MoveTemp(XmlRow));
	OutRows.Append(MoveTemp(Dependencies));
	Context.Chain.Pop();
	Context.ActiveClasses.Remove(Identity);
	return true;
}

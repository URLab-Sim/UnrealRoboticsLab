// A shared, immutable instance carrying only the schema defaults: the
// lowest-priority layer of the class merge, without a NewObject per
// query. Game thread only, and never handed out mutably.
template <class T>
const T& SchemaDefaults()
{
	static T* Prototype = nullptr;
	if (Prototype == nullptr)
	{
		Prototype = NewObject<T>(GetTransientPackage(), NAME_None, RF_Transient);
		Prototype->AddToRoot();
		ApplyDefault(*Prototype);
	}
	return *Prototype;
}


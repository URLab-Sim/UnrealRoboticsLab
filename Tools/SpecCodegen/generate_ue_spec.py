def main():
    parser = argparse.ArgumentParser()
    plugin_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    parser.add_argument("--mujoco-dir", default=os.path.join(plugin_root, "third_party", "MuJoCo", "src"))
    parser.add_argument("--out-public", default=os.path.join(plugin_root, "Source", "URLab", "Public", "MuJoCoSpec", "Generated"))
    parser.add_argument("--out-private", default=os.path.join(plugin_root, "Source", "URLab", "Private", "MuJoCoSpec", "Generated"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import manifest  # type: ignore

    enums_mod, structs_mod = load_introspect(args.mujoco_dir)
    schema_dims = parse_mjcf_schema_dims(os.path.join(args.mujoco_dir, "src", "xml", "mjcf.schema"))

    os.makedirs(args.out_public, exist_ok=True)
    os.makedirs(args.out_private, exist_ok=True)

    enums_h = emit_enums_h(enums_mod, manifest)
    structs_h, struct_fields = emit_structs_h(structs_mod, schema_dims, manifest)
    marshal_h = emit_marshal_h(manifest)
    marshal_cpp = emit_marshal_cpp(struct_fields, manifest)

    outputs = [
        (os.path.join(args.out_public, "MJSpecEnums.h"), enums_h),
        (os.path.join(args.out_public, "MJSpecStructs.h"), structs_h),
        (os.path.join(args.out_public, "MJSpecMarshal.h"), marshal_h),
        (os.path.join(args.out_private, "MJSpecMarshal.cpp"), marshal_cpp),
    ]
    if args.check:
        for path, expected in outputs:
            if not os.path.isfile(path):
                print(f"Missing generated file: {path}", file=sys.stderr)
                sys.exit(1)
            with open(path, "r", encoding="utf-8") as f:
                if f.read() != expected:
                    print(f"Drift detected in: {path}", file=sys.stderr)
                    sys.exit(1)
        print("SpecCodegen outputs are up to date.")
        return

    for path, content in outputs:
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)

    print(f"Generated codegen outputs in {args.out_public} and {args.out_private}")


if __name__ == "__main__":
    main()

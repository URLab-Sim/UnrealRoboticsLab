#!/usr/bin/env python3
"""Generate UE 5.7 UENUM, USTRUCT, and mjSpec marshaling code from MuJoCo 4 introspect + mjcf.schema."""

import argparse
import os
import re
import sys
import types


def load_introspect(mujoco_dir: str):
    mj_root = os.path.join(mujoco_dir, "python", "mujoco")
    pkg = types.ModuleType("mujoco")
    pkg.__path__ = [mj_root]
    sys.modules["mujoco"] = pkg
    from mujoco.introspect import enums, structs  # type: ignore
    return enums, structs


def parse_mjcf_schema_dims(schema_path: str):
    """Parse element -> {field_name: {'dim': ..., 'is_ref': bool}} from mjcf.schema."""
    result = {}
    if not os.path.isfile(schema_path):
        return result

    cur_struct = None
    brace_depth = 0
    elem_re = re.compile(r"^\s*element\s+\w+\s*:\s*(mjs\w+)")
    attr_re = re.compile(r"^\s*(\w+)\s*:\s*([^\s=(]+)(?:\s*=\s*[^(#]+)?(?:\s*\(([^)]*)\))?")

    with open(schema_path, "r", encoding="utf-8") as f:
        for line in f:
            stripped = line.split("#", 1)[0].strip()
            if not stripped:
                continue
            m_elem = elem_re.match(stripped)
            if m_elem and "{" in stripped:
                cur_struct = m_elem.group(1)
                brace_depth = stripped.count("{") - stripped.count("}")
                result.setdefault(cur_struct, {})
                continue
            if cur_struct is not None:
                brace_depth += stripped.count("{") - stripped.count("}")
                if brace_depth <= 0:
                    cur_struct = None
                    brace_depth = 0
                    continue
                m_attr = attr_re.match(stripped)
                if m_attr:
                    attr_name, attr_type, facets = m_attr.group(1), m_attr.group(2), m_attr.group(3) or ""
                    field_name = attr_name
                    m_field = re.search(r"field\s*=\s*(\w+)", facets)
                    if m_field:
                        field_name = m_field.group(1)
                    dim = None
                    m_dim = re.search(r'dim\s*=\s*(?:"([^"]+)"|([^\s,)]+))', facets)
                    if m_dim:
                        dim = m_dim.group(1) or m_dim.group(2)
                    is_ref = attr_type.startswith("ref<")
                    result[cur_struct][field_name] = {"dim": dim, "is_ref": is_ref}
    return result


def pascal_case_enum_val(c_name: str, prefix: str) -> str:
    raw = c_name
    if raw.startswith(prefix):
        raw = raw[len(prefix):]
    parts = [p for p in raw.split("_") if p]
    out = "".join(p[0].upper() + p[1:].lower() if p else "" for p in parts)
    if not out or out[0].isdigit():
        out = "Val_" + out
    if out.lower() in ("true", "false"):
        out = "Mj" + out
    return out


def enum_prefix(c_enum_name: str, values: dict) -> str:
    keys = [k for k in values.keys() if not k.startswith("mjN")]
    if not keys:
        return "mj"
    prefix = os.path.commonprefix(keys)
    if "_" in prefix:
        prefix = prefix[: prefix.rfind("_") + 1]
    return prefix


_COLLIDING_ENUM_PREFIX_OVERRIDES = {
    "mjtColorSpace": "EMJSpecColorSpace",
    "mjtCone": "EMJSpecCone",
    "mjtDataType": "EMJSpecDataType",
    "mjtIntegrator": "EMJSpecIntegrator",
    "mjtLightType": "EMJSpecLightType",
    "mjtMeshInertia": "EMJSpecMeshInertia",
}


def ue_enum_name(c_enum_name: str) -> str:
    if c_enum_name in _COLLIDING_ENUM_PREFIX_OVERRIDES:
        return _COLLIDING_ENUM_PREFIX_OVERRIDES[c_enum_name]
    # mjtGeom -> EMJGeom
    if c_enum_name.startswith("mjt"):
        return "EMJ" + c_enum_name[3:]
    return "EMJ" + c_enum_name


def ue_struct_name(c_struct_name: str) -> str:
    # mjsGeom -> FMJGeomSpec
    if c_struct_name.startswith("mjs"):
        return "FMJ" + c_struct_name[3:] + "Spec"
    return "FMJ" + c_struct_name + "Spec"


def pascal_field(name: str) -> str:
    parts = name.split("_")
    return "".join(p[0].upper() + p[1:] if p else "" for p in parts)


def emit_enums_h(enums_mod, manifest) -> str:
    lines = [
        "// Copyright (c) 2026 Jonathan Embley-Riches. All rights reserved. (Apache-2.0) Generated by SpecCodegen.",
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        '#include "mujoco/mujoco.h"',
        '#include "MJSpecEnums.generated.h"',
        "",
    ]

    for c_enum in manifest.TARGET_ENUMS:
        info = enums_mod.ENUMS.get(c_enum)
        if not info:
            continue
        ue_name = ue_enum_name(c_enum)
        pref = enum_prefix(c_enum, info.values)
        items = [(k, v) for k, v in info.values.items() if not k.startswith("mjN")]

        lines.append("UENUM(BlueprintType)")
        lines.append(f"enum class {ue_name} : uint8")
        lines.append("{")
        used_names = set()
        mapped = []
        for idx, (ckey, cval) in enumerate(items):
            ename = pascal_case_enum_val(ckey, pref)
            if ename in used_names:
                ename = f"{ename}_{idx}"
            used_names.add(ename)
            mapped.append((ename, ckey, cval, idx))
            lines.append(f'\t{ename} = {idx} UMETA(DisplayName = "{ckey}"),')
        lines.append("};")
        lines.append("")

        # ToMJ / FromMJ inline helpers
        lines.append(f"inline {c_enum} ToMJ({ue_name} Val)")
        lines.append("{")
        lines.append("\tswitch (Val)")
        lines.append("\t{")
        for ename, ckey, _, _ in mapped:
            lines.append(f"\tcase {ue_name}::{ename}: return {ckey};")
        lines.append(f"\tdefault: return {items[0][0]};")
        lines.append("\t}")
        lines.append("}")
        lines.append("")

        lines.append(f"inline {ue_name} FromMJ({c_enum} Val)")
        lines.append("{")
        lines.append("\tswitch (Val)")
        lines.append("\t{")
        seen_cvals = set()
        for ename, ckey, cval, _ in mapped:
            if cval in seen_cvals:
                continue
            seen_cvals.add(cval)
            lines.append(f"\tcase {ckey}: return {ue_name}::{ename};")
        lines.append(f"\tdefault: return {ue_name}::{mapped[0][0]};")
        lines.append("\t}")
        lines.append("}")
        lines.append("")

    # Actuator shortcut enum
    lines.append("UENUM(BlueprintType)")
    lines.append("enum class EMJActuatorShortcut : uint8")
    lines.append("{")
    for idx, (sname, cconst) in enumerate(manifest.ACTUATOR_SHORTCUTS):
        lines.append(f'\t{sname} = {idx} UMETA(DisplayName = "{sname}"),')
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def classify_field(struct_name: str, field, schema_dims: dict, manifest):
    fname = field.name
    ftype = str(field.type).strip()
    skip_all = manifest.SKIP_FIELDS.get("*", set())
    skip_struct = manifest.SKIP_FIELDS.get(struct_name, set())
    if fname in skip_all or fname in skip_struct:
        return None

    # Check if type is unsupported struct/pointer
    if ftype in ("mjsElement *", "mjsOrientation", "mjsPlugin", "mjByteVec *"):
        return None

    unit_rule = manifest.FIELD_UNIT_OVERRIDES.get(f"{struct_name}.{fname}")
    if unit_rule is None:
        sinfo = schema_dims.get(struct_name, {}).get(fname, {})
        dim = sinfo.get("dim")
        if dim == "L":
            unit_rule = "len"
        elif dim == "A":
            unit_rule = "angle"

    # Special fromto handling
    if unit_rule == "fromto" and ftype == "double [6]":
        return {
            "kind": "fromto",
            "c_name": fname,
            "ue_name": pascal_field(fname),
        }

    if unit_rule == "vec3_pos" and ftype in ("double [3]", "float [3]"):
        return {
            "kind": "vec3_pos",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "FVector",
            "default": "FVector::ZeroVector",
            "c_elem": "double" if "double" in ftype else "float",
        }

    if unit_rule == "vec3_dir" and ftype in ("double [3]", "float [3]"):
        return {
            "kind": "vec3_dir",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "FVector",
            "default": "FVector(0.0, 0.0, 1.0)",
            "c_elem": "double" if "double" in ftype else "float",
        }

    if unit_rule == "vec3_scale" and ftype in ("double [3]", "float [3]"):
        return {
            "kind": "vec3_raw",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "FVector",
            "default": "FVector(1.0, 1.0, 1.0)",
            "c_elem": "double" if "double" in ftype else "float",
        }

    if unit_rule == "quat" and ftype in ("double [4]", "float [4]"):
        return {
            "kind": "quat",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "FQuat",
            "default": "FQuat::Identity",
            "c_elem": "double" if "double" in ftype else "float",
        }

    if ftype == "mjtBool":
        return {
            "kind": "bool",
            "c_name": fname,
            "ue_name": "b" + pascal_field(fname),
            "ue_type": "bool",
            "default": "false",
        }

    if ftype in [e for e in manifest.TARGET_ENUMS]:
        ue_t = ue_enum_name(ftype)
        return {
            "kind": "enum",
            "c_name": fname,
            "c_type": ftype,
            "ue_name": pascal_field(fname),
            "ue_type": ue_t,
            "default": f"{ue_t}(0)",
        }

    if ftype in ("int",):
        return {
            "kind": "scalar",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "int32",
            "c_type": "int",
            "default": "0",
            "unit": None,
        }

    if ftype in ("mjtByte", "uint8_t"):
        return {
            "kind": "scalar",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "uint8",
            "c_type": ftype,
            "default": "0",
            "unit": None,
        }

    if ftype in ("double", "mjtNum", "float"):
        ue_t = "float" if ftype == "float" else "double"
        return {
            "kind": "scalar",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": ue_t,
            "c_type": ftype,
            "default": "0.0f" if ue_t == "float" else "0.0",
            "unit": unit_rule,
        }

    if ftype == "mjString *":
        return {
            "kind": "string",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "FString",
            "default": "",
        }

    m_char = re.match(r"char\s*\[(\d+)\]", ftype)
    if m_char:
        return {
            "kind": "char_arr",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": "FString",
            "size": int(m_char.group(1)),
            "default": "",
        }

    m_arr = re.match(r"(double|float|int|mjtNum)\s*\[(\d+)\]", ftype)
    if m_arr:
        base, count = m_arr.group(1), int(m_arr.group(2))
        if fname == "rgba" and count == 4:
            return {
                "kind": "rgba",
                "c_name": fname,
                "ue_name": "Rgba",
                "ue_type": "FLinearColor",
                "default": "FLinearColor(0.5f, 0.5f, 0.5f, 1.0f)",
            }
        ue_elem = "int32" if base == "int" else ("float" if base == "float" else "double")
        return {
            "kind": "fixed_arr",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": f"TArray<{ue_elem}>",
            "ue_elem": ue_elem,
            "c_elem": base,
            "count": count,
            "unit": unit_rule,
        }

    if ftype in ("mjDoubleVec *", "mjFloatVec *", "mjIntVec *", "mjStringVec *"):
        vec_map = {
            "mjDoubleVec *": ("double", "mjDoubleVec", "Double"),
            "mjFloatVec *": ("float", "mjFloatVec", "Float"),
            "mjIntVec *": ("int32", "mjIntVec", "Int"),
            "mjStringVec *": ("FString", "mjStringVec", "String"),
        }
        ue_elem, mj_vec, fn_sfx = vec_map[ftype]
        return {
            "kind": "vec",
            "c_name": fname,
            "ue_name": pascal_field(fname),
            "ue_type": f"TArray<{ue_elem}>",
            "ue_elem": ue_elem,
            "mj_vec": mj_vec,
            "fn_sfx": fn_sfx,
        }

    return None


def emit_structs_h(structs_mod, schema_dims, manifest) -> tuple[str, dict]:
    lines = [
        "// Copyright (c) 2026 Jonathan Embley-Riches. All rights reserved. (Apache-2.0) Generated by SpecCodegen.",
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        '#include "Generated/MJSpecEnums.h"',
        '#include "MJSpecStructs.generated.h"',
        "",
    ]

    struct_fields = {}
    for sname in manifest.TARGET_STRUCTS:
        sdef = structs_mod.STRUCTS[sname]
        ue_sname = ue_struct_name(sname)
        classified = []
        for f in sdef.fields:
            cf = classify_field(sname, f, schema_dims, manifest)
            if cf is not None:
                classified.append(cf)
        struct_fields[sname] = classified

        lines.append("USTRUCT(BlueprintType)")
        lines.append(f"struct URLAB_API {ue_sname}")
        lines.append("{")
        lines.append("\tGENERATED_BODY()")
        lines.append("")

        for cf in classified:
            if cf["kind"] == "fromto":
                lines.append('\tUPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MuJoCo|Override", meta = (InlineEditConditionToggle))')
                lines.append("\tbool bOverride_FromTo = false;")
                lines.append("")
                lines.append('\tUPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MuJoCo|Spec", meta = (EditCondition = "bOverride_FromTo"))')
                lines.append("\tbool bUseFromTo = false;")
                lines.append("")
                lines.append('\tUPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MuJoCo|Spec", meta = (EditCondition = "bOverride_FromTo && bUseFromTo"))')
                lines.append("\tFVector From = FVector::ZeroVector;")
                lines.append("")

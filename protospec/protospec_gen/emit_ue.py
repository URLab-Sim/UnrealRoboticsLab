# --------------------------------------------------------------------------- #
# Generated coverage test                                                      #
# --------------------------------------------------------------------------- #
def emit_coverage(s: UeSchema) -> str:
    """The schema-coverage assertion, generated from the schema rather than
    written by hand: every element has a registered UCLASS, every attribute a
    registered FProperty of the expected storage, every enum a UENUM whose
    enumerator order matches the schema.

    One function per element and per enum, rather than one body over the whole
    schema: a schema this size makes a single function tens of thousands of
    instructions long, which MSVC reports as C4883 (function size suppresses
    optimizations) and UE promotes to an error. The split also puts the failing
    element's name in the stack frame."""
    o: list[str] = []
    w = o.append
    w(LICENSE.rstrip("\n"))
    w("")
    w(BANNER)
    w("//")
    w("// Schema coverage, asserted against UE's own reflection rather than")
    w("// against the emitter's intent: a property that failed to register (a")
    w("// storage type UHT silently dropped, a specifier that produced a bad_type)")
    w("// is invisible at compile time and fails here.")
    w("")
    w('#include "CoreMinimal.h"')
    w('#include "Misc/AutomationTest.h"')
    w("")
    w('#include "MuJoCo/Spec/MjGenHooks.h"')
    w("")
    w("#if URLAB_MJ_GEN && WITH_DEV_AUTOMATION_TESTS")
    w("")
    w('#include "UObject/UnrealType.h"')
    w("")
    w('#include "MuJoCo/Gen/MjElements.gen.h"')
    w('#include "MuJoCo/Gen/MjEnums.gen.h"')
    w("")
    w("IMPLEMENT_SIMPLE_AUTOMATION_TEST(FMjGenSchemaCoverageTest,")
    w('\t"URLab.Gen.SchemaCoverage",')
    w("\tEAutomationTestFlags::EditorContext | EAutomationTestFlags::EngineFilter)")
    w("")
    w("namespace")
    w("{")
    w("bool HasProperty(FAutomationTestBase& Test, UClass* Class,")
    w("\tconst TCHAR* PropertyName)")
    w("{")
    w("\tconst FProperty* Property = Class->FindPropertyByName(FName(PropertyName));")
    w("\tif (Property == nullptr)")
    w("\t{")
    w("\t\tTest.AddError(FString::Printf(TEXT(\"%s has no property %s\"),")
    w("\t\t\t*Class->GetName(), PropertyName));")
    w("\t\treturn false;")
    w("\t}")
    w("\treturn true;")
    w("}")
    w("")
    w("bool HasFunction(FAutomationTestBase& Test, UClass* Class,")
    w("\tconst TCHAR* FunctionName)")
    w("{")
    w("\tif (Class->FindFunctionByName(FName(FunctionName)) == nullptr)")
    w("\t{")
    w("\t\tTest.AddError(FString::Printf(TEXT(\"%s has no function %s\"),")
    w("\t\t\t*Class->GetName(), FunctionName));")
    w("\t\treturn false;")
    w("\t}")
    w("\treturn true;")
    w("}")
    for e in s.elements:
        cls = s.cls[e["name"]]
        w("")
        w(f"// <{e['xml']}>")
        w(f"void CoverElement{e['name']}(FAutomationTestBase& Test)")
        w("{")
        w(f"\tUClass* const Class = {cls}::StaticClass();")
        w(f'\tTest.TestNotNull(TEXT("{cls} is registered"), Class);')
        for _fid, f in s.stored_fields(e):
            member = s.member(e, f)
            w(f'\tHasProperty(Test, Class, TEXT("{member}"));')
            w(f'\tHasFunction(Test, Class, TEXT("Get{member}"));')
            w(f'\tHasFunction(Test, Class, TEXT("Set{member}"));')
            w(f'\tHasFunction(Test, Class, TEXT("Has{member}"));')
            if f["optional"]:
                w(f'\tHasFunction(Test, Class, TEXT("Clear{member}"));')
        w("}")
    for en in s.enums:
        name = s.enum[en["name"]]
        w("")
        w(f"void CoverEnum{en['name']}(FAutomationTestBase& Test)")
        w("{")
        w(f"\tUEnum* const Enum = StaticEnum<{name}>();")
        w(f'\tTest.TestNotNull(TEXT("{name} is registered"), Enum);')
        w("\tif (Enum == nullptr)")
        w("\t{")
        w("\t\treturn;")
        w("\t}")
        w(f'\tTest.TestEqual(TEXT("{name} keyword count"),')
        w(f"\t\tEnum->NumEnums() - 1, {len(en['members'])});")
        for i, m in enumerate(en["members"]):
            w(f'\tTest.TestEqual(TEXT("{name}[{i}] keyword"),')
            w(f"\t\tEnum->GetDisplayNameTextByIndex({i}).ToString(),")
            w(f'\t\tFString(TEXT("{cpp_str(m["value"])}")));')
        w("}")
    w("}  // namespace")
    w("")
    w("bool FMjGenSchemaCoverageTest::RunTest(const FString& Parameters)")
    w("{")
    for e in s.elements:
        w(f"\tCoverElement{e['name']}(*this);")
    w("")
    for en in s.enums:
        w(f"\tCoverEnum{en['name']}(*this);")
    w("")
    w("\treturn !HasAnyErrors();")
    w("}")
    w("")
    w("#endif  // URLAB_MJ_GEN && WITH_DEV_AUTOMATION_TESTS")
    return "\n".join(o) + "\n"



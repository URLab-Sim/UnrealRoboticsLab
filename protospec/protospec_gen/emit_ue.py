# Visit                                                                        #
# --------------------------------------------------------------------------- #
def emit_visit(s: UeSchema) -> str:
    o: list[str] = []
    w = o.append
    w(LICENSE.rstrip("\n"))
    w("")
    w(BANNER)
    w("//")
    w("// The generated Visit hook: one traversal, N consumers. V receives every")
    w("// attribute by schema field id + MJCF name + typed reference. Field ids")
    w("// are the SCHEMA's, shared with every other profile and with the reflect")
    w("// and xml_binding tables, so a table-driven reader and writer need no")
    w("// knowledge of UE storage.")
    w("//")
    w("// No child calls: the attachment hierarchy is the child list, so children")
    w("// reach the SDK through the tree adapter (MjDispatch.gen.h supplies the")
    w("// per-element storage slots it needs) rather than through Visit.")
    w("//")
    w("// A reference field is handed over wrapped, because its storage -- a")
    w("// name string -- is indistinguishable from a plain string attribute and")
    w("// the reference scan must be able to tell them apart at compile time.")
    w("// The wrapper is the one hand seam this file needs:")
    w("//")
    w("//   template <class Target, class SlotType = TOptional<FString>>")
    w("//   struct RefView            // urlab, MuJoCo/Spec/MjRefView.h")
    w("//   {")
    w("//     SlotType& Slot;                       // aggregate-initialized")
    w("//     using TargetType = Target;            // phantom, as ps::Ref<T>")
    w("//     bool IsSet() const;                   // set AND non-empty")
    w("//     FStringView Get() const;")
    w("//     void Set(FStringView Name) const;     // empty name clears")
    w("//     void Clear() const;")
    w("//     SlotType* SlotPtr() const { return &Slot; }")
    w("//   };")
    w("//")
    w("// SlotType is spelled explicitly at every call below, because a required")
    w("// reference stores a plain FString and the const traversal binds a const")
    w("// slot; Set/Clear must be constrained out when SlotType is const.")
    w("// SlotPtr matters: the view itself is a temporary that dies with the")
    w("// Visit frame, so a Ref policy handing out a RefSlot must build its ops")
    w("// over the storage the view points at, never over the view.")
    w("#pragma once")
    w("")
    w('#include <utility>')
    w("")
    w('#include "MuJoCo/Spec/MjRefView.h"')
    w('#include "MuJoCo/Gen/MjElements.gen.h"')
    w("")
    w("namespace ps::ue")
    w("{")
    for e in s.elements:
        for const in (False, True):
            _visit_one(s, e, const, w)
    w("}  // namespace ps::ue")
    return "\n".join(o) + "\n"


def _visit_one(s: UeSchema, elem: dict, const: bool, w) -> None:
    cls = s.cls[elem["name"]]
    qual = "const " if const else ""
    w("")
    w("template <class V>")
    w(f"void Visit({qual}{cls}& Element, V&& Vis)")
    w("{")
    body = False
    for fid, f in enumerate(elem["fields"]):
        xml = f["xml"]
        if UeSchema.is_identity(f):
            w(f'\tVis.field({fid}, "{xml}", Element.MjName);')
            body = True
            continue
        member = s.member(elem, f)
        if f["type"]["kind"] == "ref":
            slot = "FString" if not f["optional"] else "TOptional<FString>"
            if const:
                slot = f"const {slot}"
            target = s.ref_target(f)
            w(f"\turlab::RefView<{target}, {slot}> Ref{fid}{{ Element.{member} }};")
            w(f'\tVis.field({fid}, "{xml}", Ref{fid});')
        else:
            w(f'\tVis.field({fid}, "{xml}", Element.{member});')
        body = True
    if not body:
        w("\t(void)Element;")
    w("\t(void)Vis;")
    w("}")



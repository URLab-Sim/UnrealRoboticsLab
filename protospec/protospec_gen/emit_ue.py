    w("\telse if constexpr (TIsArray<I>::value)")
    w("\t{")
    w("\t\tif constexpr (std::is_enum_v<typename TIsArray<I>::Element>)")
    w("\t\t\treturn sdk::Shape::EnumList;")
    w("\t\telse")
    w("\t\t\treturn sdk::Shape::Unbounded;")
    w("\t}")
    w("\telse if constexpr (std::is_arithmetic_v<I>) { return sdk::Shape::Scalar; }")
    w("\telse { return sdk::Shape::Unknown; }")
    w("}")
    w("}  // namespace storage")
    w("")
    w("struct FMjShape")
    w("{")
    w("\ttemplate <class T>")
    w("\tstatic constexpr bool optional_v =")
    w("\t\tstorage::TIsOptional<std::decay_t<T>>::value ||")
    w("\t\tstorage::TIsRefView<std::decay_t<T>>::value;")
    w("")
    w("\ttemplate <class T>")
    w("\tusing inner_t = typename storage::TInnerOf<std::decay_t<T>>::Type;")
    w("")
    w("\ttemplate <class T>")
    w("\tstatic bool IsSet(const T& Slot)")
    w("\t{")
    w("\t\tif constexpr (storage::TIsRefView<std::decay_t<T>>::value)")
    w("\t\t\treturn Slot.IsSet();")
    w("\t\telse if constexpr (storage::TIsOptional<std::decay_t<T>>::value)")
    w("\t\t\treturn Slot.IsSet();")
    w("\t\telse")
    w("\t\t\treturn true;")
    w("\t}")
    w("")
    w("\t// A reference slot has no stored FMjRefName to hand back, so this")
    w("\t// returns by value there; callers bind the result to a const reference,")
    w("\t// which extends its lifetime.")
    w("\ttemplate <class T>")
    w("\tstatic decltype(auto) Read(const T& Slot)")
    w("\t{")
    w("\t\tif constexpr (storage::TIsRefView<std::decay_t<T>>::value)")
    w("\t\t\treturn FMjRefName{ FString(Slot.Get()) };")
    w("\t\telse if constexpr (storage::TIsOptional<std::decay_t<T>>::value)")
    w("\t\t\treturn (Slot.GetValue());")
    w("\t\telse")
    w("\t\t\treturn (Slot);")
    w("\t}")
    w("")
    w("\ttemplate <class T>")
    w("\tstatic void Author(T& Slot, inner_t<T> Value)")
    w("\t{")
    w("\t\tif constexpr (storage::TIsRefView<std::decay_t<T>>::value)")
    w("\t\t\tSlot.Set(FStringView(Value.Name));")
    w("\t\telse")
    w("\t\t\tSlot = MoveTemp(Value);")
    w("\t}")
    w("")
    w("\ttemplate <class T>")
    w("\tstatic void Reset(T& Slot)")
    w("\t{")
    w("\t\tif constexpr (storage::TIsRefView<std::decay_t<T>>::value)")

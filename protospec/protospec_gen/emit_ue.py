def child_slots(s: UeSchema, elem: dict) -> list[tuple[int, str, str]]:
    """(storage slot, child element name, contextual XML tag) for every element
    type this element admits as a child.

    The slot is the schema child index, which is what the writer indexes to
    recover a contextual tag (<worldbody> for a body under the model, <joint>
    for a composite's joint) and what the reader groups its child pass by.
    """
    out: list[tuple[int, str, str]] = []
    for slot, c in enumerate(elem["children"]):
        if c.get("union") is not None:
            for m in s.union_by_name[c["union"]]["members"]:
                out.append((slot, m, s.element_by_name[m]["xml"]))
        else:
            out.append((slot, c["element"], c["tag"]))
    return out


def emit_dispatch_h(s: UeSchema) -> str:
    o: list[str] = []
    w = o.append
    w(LICENSE.rstrip("\n"))
    w("")
    w(BANNER)
    w("//")
    w("// Per-element dispatch: everything a tree adapter, a node factory or a")
    w("// details customization needs to get from a runtime element identity to a")
    w("// concrete generated class, and back. All of it scales with the schema, so")
    w("// none of it is a hand-written switch.")
    w("//")
    w("// ChildSlots is the contract the tree adapters implement ForEachChildSlot")
    w("// against: it enumerates, per element type, the storage slots it admits")
    w("// and the concrete class each slot accepts. The slot number is the schema")
    w("// child index, so the writer recovers the contextual tag from the shared")
    w("// binding table and the reader groups its child pass by it.")
    w("#pragma once")
    w("")
    w("#include <type_traits>")
    w("#include <utility>")
    w("")
    w('#include "CoreMinimal.h"')
    w('#include "Components/SceneComponent.h"')
    w("")
    w('#include "MuJoCo/Gen/MjElements.gen.h"')
    w('#include "protospec/profile.h"')
    w("")
    w("namespace ps::ue")
    w("{")
    w("using ps::mjcf::ElementType;")
    w("")
    w("// --- Schema identity of a generated class ------------------------- //")
    w("template <class E> struct TMjElementType;")
    w("template <ElementType E> struct TMjElementOf;")
    w("")
    for e in s.elements:
        cls = s.cls[e["name"]]
        w(f"template <> struct TMjElementType<{cls}>")
        w(f"{{ static constexpr ElementType Value = ElementType::{e['name']}; }};")
    w("")
    for e in s.elements:
        cls = s.cls[e["name"]]
        w(f"template <> struct TMjElementOf<ElementType::{e['name']}>")
        w(f"{{ using Type = {cls}; }};")
    w("")
    w("// The element types a reference field may name: one for a concrete")
    w("// target, every declarer of the namespace for a shared one. The typed")
    w("// half of what detail::RefTargetsAt answers at runtime.")
    w("template <class Target> struct TMjRefTargets;")
    w("")
    for e in s.elements:
        w(f"template <> struct TMjRefTargets<{s.cls[e['name']]}>")
        w(f"{{ static constexpr ElementType Types[] = "
          f"{{ ElementType::{e['name']} }}; }};")
    for u in s.unions:
        members = ", ".join(f"ElementType::{m}" for m in u["members"])
        w(f"template <> struct TMjRefTargets<{s.union_tag[u['name']]}>")
        w(f"{{ static constexpr ElementType Types[] = {{ {members} }}; }};")
    w("")
    w("// True when the schema gives the element an identity attribute, so its")
    w("// MjName is authored data rather than an always-empty slot.")
    w("template <class E> struct TMjHasName : std::false_type {};")
    for e in s.elements:
        if s.has_identity(e):
            w(f"template <> struct TMjHasName<{s.cls[e['name']]}> : std::true_type {{}};")
    w("")
    w("// --- Runtime tables ------------------------------------------------ //")
    w("// Exported as a set. This is a public header of the URLab module, and the")
    w("// editor module asks these tables the same questions the runtime does:")
    w("// what an element is, what it is called, where a child may be placed.")
    w("// Declaring them here unexported turns each one into a link error at the")
    w("// moment a second module first calls it, which is a fact about the module")
    w("// boundary rather than about the caller, and exporting them one at a time")
    w("// as that happens leaves the surface arbitrary.")
    w("/** The generated class an element type names, or null. */")
    w("URLAB_API UClass* ClassForElement(ElementType Type);")
    w("")
    w("/** The element type a class (or the nearest generated base of a")
    w(" *  presentation subclass) names. False when it is not a spec node. */")
    w("URLAB_API bool ElementTypeOfClass(const UClass* Class, ElementType& Out);")
    w("")
    w("/** As above, for a live node. */")
    w("URLAB_API bool ElementTypeOfNode(const UMjNodeComponent& Node, ElementType& Out);")
    w("")
    w("/** The element's own MJCF tag (what it is called at the top level). */")
    w("URLAB_API const TCHAR* TagForElement(ElementType Type);")
    w("")
    w("/** The element a top-level MJCF tag names. */")
    w("URLAB_API bool ElementTypeForTag(FStringView Tag, ElementType& Out);")
    w("")
    w("/** The element a tag names IN CONTEXT, which is not always the same: the")
    w(" *  schema routes <worldbody> to a body and <joint> under <composite> to a")
    w(" *  composite joint. Reports the storage slot the child would occupy. */")
    w("URLAB_API bool ElementTypeForChildTag(ElementType Parent, FStringView Tag,")
    w("\tElementType& OutChild, int32& OutSlot);")
    w("")
    w("/** The tag a child of this type is WRITTEN as under this parent. */")
    w("URLAB_API const TCHAR* ChildTagFor(ElementType Parent, ElementType Child);")
    w("")
    w("/** The storage slot a child of this type occupies under this parent, or")
    w(" *  -1 when the parent does not admit it. */")
    w("URLAB_API int32 SlotFor(ElementType Parent, ElementType Child);")
    w("")
    w("/** Every (slot, admissible child type) pair a parent admits. */")
    w("URLAB_API void ForEachAdmissibleChild(ElementType Parent,")
    w("\tTFunctionRef<void(int32 Slot, ElementType Child)> Fn);")
    w("")
    w("/** Names of every element in the spec that a reference field could")
    w(" *  legally point at: the backing of every generated GetOptions dropdown. */")
    w("URLAB_API TArray<FString> RefNameOptions(const UMjNodeComponent* Node, int32 FieldId);")
    w("")
    w("// --- What the tables cost ------------------------------------------ //")
    w("// `DispatchLookups` counts calls that consult a table above;")
    w("// `DispatchRowVisits` counts the rows examined answering them. The ratio")
    w("// is the shape of the lookup: about one row per call is a hashed hit, and")
    w("// the table's height is a scan. Every element of a model is dispatched")
    w("// several times over during an import, so the difference between the two")
    w("// is the difference between a table and a search. The import benchmark")
    w("// asserts on the ratio, which is what stops a scan coming back.")
    w("//")
    w("// Monotonic since process start; take deltas around the work of interest.")
    w("URLAB_API int64 DispatchLookups();")
    w("URLAB_API int64 DispatchRowVisits();")
    w("")
    w("// --- Compile-time dispatch ----------------------------------------- //")
    w("// The storage slots an element admits, as (slot, TypeTag<Class>). The")
    w("// overload set is the schema's; a tree adapter forwards to it.")
    for e in s.elements:
        slots = child_slots(s, e)
        w("")
        w("template <class Fn>")
        w(f"void ChildSlots(const {s.cls[e['name']]}*, Fn&& Callback)")
        w("{")
        if not slots:
            w("\t(void)Callback;")
        for slot, child, _tag in slots:
            w(f"\tCallback({slot}, ps::sdk::TypeTag<{s.cls[child]}>{{}});")
        w("}")
    w("")
    w("// Recover a node's concrete generated type. The 144-way switch is the")
    w("// profile's business, not an algorithm's.")
    w("template <class Fn>")
    w("bool DispatchByType(UMjNodeComponent& Node, Fn&& Callback)")
    w("{")
    w("\tElementType Type;")
    w("\tif (!ElementTypeOfNode(Node, Type)) return false;")
    w("\tswitch (Type)")
    w("\t{")
    for e in s.elements:
        cls = s.cls[e["name"]]
        w(f"\tcase ElementType::{e['name']}:")
        w(f"\t\tCallback(static_cast<{cls}&>(Node)); return true;")
    w("\tdefault: return false;")
    w("\t}")
    w("}")
    w("")
    w("template <class Fn>")
    w("bool DispatchByType(const UMjNodeComponent& Node, Fn&& Callback)")
    w("{")
    w("\treturn DispatchByType(const_cast<UMjNodeComponent&>(Node),")
    w("\t\t[&](auto& Element)")
    w("\t\t{ Callback(static_cast<const std::decay_t<decltype(Element)>&>(Element)); });")
    w("}")
    w("")
    w("}  // namespace ps::ue")
    return "\n".join(o) + "\n"


def emit_dispatch_cpp(s: UeSchema) -> str:
    o: list[str] = []
    w = o.append
    w(LICENSE.rstrip("\n"))
    w("")
    w(BANNER)
    w("")
    w('#include "MuJoCo/Gen/MjDispatch.gen.h"')
    w("")
    w("#include <atomic>")
    w("#include <vector>")
    w("")
    w('#include "protospec/detail.h"')
    w("")
    w("namespace ps::ue")
    w("{")
    w("namespace")
    w("{")
    w("std::atomic<int64> GLookups{0};")
    w("std::atomic<int64> GRowVisits{0};")
    w("")
    w("// Relaxed: these are a cost meter read once at the end of a benchmark, not")
    w("// a synchronization edge, and a lookup must not pay for a fence.")
    w("void NoteLookup(int32 RowsVisited)")
    w("{")
    w("\tGLookups.fetch_add(1, std::memory_order_relaxed);")
    w("\tGRowVisits.fetch_add(RowsVisited, std::memory_order_relaxed);")
    w("}")
    w("")
    w("struct FElementRow")
    w("{")
    w("\tElementType Type;")
    w("\tUClass* (*StaticClassFn)();")
    w("\tconst TCHAR* Tag;")
    w("};")
    w("")
    w("const FElementRow* ElementRows(int32& OutCount)")
    w("{")
    w("\tstatic const FElementRow Rows[] = {")
    for e in s.elements:
        cls = s.cls[e["name"]]
        w(f'\t\t{{ ElementType::{e["name"]}, &{cls}::StaticClass, '
          f'TEXT("{cpp_str(e["xml"])}") }},')
    w("\t};")
    w("\tOutCount = UE_ARRAY_COUNT(Rows);")
    w("\treturn Rows;")
    w("}")
    w("")
    w("struct FChildRow")
    w("{")
    w("\tElementType Parent;")
    w("\tint32 Slot;")
    w("\tElementType Child;")
    w("\tconst TCHAR* Tag;")
    w("};")
    w("")
    w("// One row per (parent, storage slot, admissible child type). The tag is")
    w("// the CONTEXTUAL one: what the schema calls that child under that parent.")
    w("const FChildRow* ChildRows(int32& OutCount)")
    w("{")
    w("\tstatic const FChildRow Rows[] = {")
    total = 0
    for e in s.elements:
        for slot, child, tag in child_slots(s, e):
            total += 1
            w(f'\t\t{{ ElementType::{e["name"]}, {slot}, ElementType::{child}, '
              f'TEXT("{cpp_str(tag)}") }},')
    if total == 0:
        w("\t\t{},")
    w("\t};")
    w("\tOutCount = UE_ARRAY_COUNT(Rows);")
    w("\treturn Rows;")
    w("}")
    w("")
    w("// The tables above are answered from these, never by scanning. Every")
    w("// element of a model is resolved to a class, a tag and a storage slot")
    w("// several times over while it is read, so the height of a table used to")
    w("// multiply the size of the model.")
    w("//")
    w("// Built once, on first use rather than at static-initialisation time,")
    w("// because a row's class is a UClass and asking for one before the object")
    w("// system is up is undefined.")
    w("struct FDispatchIndex")
    w("{")
    w("\t/** Element rows, by schema type, by concrete class, by tag hash. */")
    w("\tTMap<int32, int32> ByType;")
    w("\tTMap<const UClass*, int32> ByClass;")
    w("\tTMultiMap<uint32, int32> ByTagHash;")
    w("")
    w("\t/** Child rows, by (parent, child), and the row span of each parent. */")
    w("\tTMap<uint64, int32> ByParentChild;")
    w("\tTMultiMap<uint64, int32> ByParentTagHash;")
    w("\tTMap<int32, TPair<int32, int32>> SpanByParent;")
    w("};")
    w("")
    w("uint64 PairKey(ElementType Parent, ElementType Child)")
    w("{")
    w("\treturn (static_cast<uint64>(Parent) << 32) | static_cast<uint32>(Child);")
    w("}")
    w("")
    w("uint64 TagKey(ElementType Parent, uint32 TagHash)")
    w("{")
    w("\treturn (static_cast<uint64>(Parent) << 32) | TagHash;")
    w("}")
    w("")
    w("const FDispatchIndex& Index()")
    w("{")
    w("\tstatic const FDispatchIndex Built = []")
    w("\t{")
    w("\t\tFDispatchIndex Out;")
    w("\t\tint32 ElementCount = 0;")
    w("\t\tconst FElementRow* Elements = ElementRows(ElementCount);")
    w("\t\tfor (int32 I = 0; I < ElementCount; ++I)")
    w("\t\t{")
    w("\t\t\t// First row wins, which is the row a scan would have stopped at.")
    w("\t\t\tOut.ByType.FindOrAdd(static_cast<int32>(Elements[I].Type), I);")
    w("\t\t\tOut.ByClass.FindOrAdd(Elements[I].StaticClassFn(), I);")
    w("\t\t\tOut.ByTagHash.Add(GetTypeHash(FStringView(Elements[I].Tag)), I);")
    w("\t\t}")
    w("\t\tint32 ChildCount = 0;")
    w("\t\tconst FChildRow* Children = ChildRows(ChildCount);")
    w("\t\tfor (int32 I = 0; I < ChildCount; ++I)")
    w("\t\t{")
    w("\t\t\tOut.ByParentChild.FindOrAdd(PairKey(Children[I].Parent, Children[I].Child), I);")
    w("\t\t\tOut.ByParentTagHash.Add(")
    w("\t\t\t\tTagKey(Children[I].Parent, GetTypeHash(FStringView(Children[I].Tag))), I);")
    w("\t\t\tconst int32 Parent = static_cast<int32>(Children[I].Parent);")
    w("\t\t\tif (TPair<int32, int32>* Span = Out.SpanByParent.Find(Parent))")
    w("\t\t\t{")
    w("\t\t\t\tSpan->Key = FMath::Min(Span->Key, I);")
    w("\t\t\t\tSpan->Value = FMath::Max(Span->Value, I + 1);")
    w("\t\t\t}")
    w("\t\t\telse")
    w("\t\t\t{")
    w("\t\t\t\tOut.SpanByParent.Add(Parent, TPair<int32, int32>(I, I + 1));")
    w("\t\t\t}")
    w("\t\t}")
    w("\t\treturn Out;")
    w("\t}();")
    w("\treturn Built;")
    w("}")
    w("")
    w("void CollectNames(const USceneComponent* Node,")
    w("\tconst std::vector<ElementType>& Targets, TArray<FString>& Out)")
    w("{")
    w("\tif (Node == nullptr) return;")
    w("\tif (const UMjNodeComponent* Doc = Cast<UMjNodeComponent>(Node))")
    w("\t{")
    w("\t\tElementType Type;")
    w("\t\tif (Doc->MjName.IsSet() && ElementTypeOfNode(*Doc, Type))")
    w("\t\t{")
    w("\t\t\tfor (ElementType Want : Targets)")
    w("\t\t\t{")
    w("\t\t\t\tif (Want == Type) { Out.AddUnique(Doc->MjName.GetValue()); break; }")
    w("\t\t\t}")
    w("\t\t}")
    w("\t}")
    w("\tfor (const USceneComponent* Child : Node->GetAttachChildren())")
    w("\t\tCollectNames(Child, Targets, Out);")
    w("}")
    w("")
    w("}  // namespace")
    w("")
    w("int64 DispatchLookups() { return GLookups.load(std::memory_order_relaxed); }")
    w("int64 DispatchRowVisits() { return GRowVisits.load(std::memory_order_relaxed); }")
    w("")
    w("UClass* ClassForElement(ElementType Type)")
    w("{")
    w("\tNoteLookup(1);")
    w("\tconst int32* Row = Index().ByType.Find(static_cast<int32>(Type));")
    w("\tif (Row == nullptr) return nullptr;")
    w("\tint32 Count = 0;")
    w("\treturn ElementRows(Count)[*Row].StaticClassFn();")
    w("}")
    w("")
    w("bool ElementTypeOfClass(const UClass* Class, ElementType& Out)")
    w("{")
    w("\tint32 Count = 0;")
    w("\tconst FElementRow* Rows = ElementRows(Count);")
    w("\tconst FDispatchIndex& Idx = Index();")
    w("\tint32 Visited = 0;")
    w("\t// A presentation subclass (UMjBox over a geom) is the element its")
    w("\t// nearest generated base names, so walk up rather than matching exactly.")
    w("\t// The walk is the class chain, which is short and fixed; what it used to")
    w("\t// cost was the whole element table at every step of it.")
    w("\tfor (const UClass* C = Class; C != nullptr; C = C->GetSuperClass())")
    w("\t{")
    w("\t\t++Visited;")
    w("\t\tif (const int32* Row = Idx.ByClass.Find(C))")
    w("\t\t{ NoteLookup(Visited); Out = Rows[*Row].Type; return true; }")
    w("\t}")
    w("\tNoteLookup(FMath::Max(Visited, 1));")
    w("\treturn false;")
    w("}")
    w("")
    w("bool ElementTypeOfNode(const UMjNodeComponent& Node, ElementType& Out)")
    w("{")
    w("\treturn ElementTypeOfClass(Node.GetClass(), Out);")
    w("}")
    w("")
    w("const TCHAR* TagForElement(ElementType Type)")
    w("{")
    w("\tNoteLookup(1);")
    w("\tconst int32* Row = Index().ByType.Find(static_cast<int32>(Type));")
    w("\tif (Row == nullptr) return TEXT(\"\");")
    w("\tint32 Count = 0;")
    w("\treturn ElementRows(Count)[*Row].Tag;")
    w("}")
    w("")
    w("bool ElementTypeForTag(FStringView Tag, ElementType& Out)")
    w("{")
    w("\tint32 Count = 0;")
    w("\tconst FElementRow* Rows = ElementRows(Count);")
    w("\t// Several elements answer to one tag -- <geom> is a body geom, a")
    w("\t// composite geom and a tendon geom -- so the lowest row wins, which is")
    w("\t// the row a scan would have stopped at. The index is keyed on a")
    w("\t// case-insensitive hash, so a hit is a candidate and the comparison")
    w("\t// below is what decides.")
    w("\tint32 Best = MAX_int32;")
    w("\tint32 Visited = 0;")
    w("\tfor (auto It = Index().ByTagHash.CreateConstKeyIterator(GetTypeHash(Tag)); It; ++It)")
    w("\t{")
    w("\t\t++Visited;")
    w("\t\tconst int32 Row = It.Value();")
    w("\t\tif (Row < Best && Tag.Equals(FStringView(Rows[Row].Tag), ESearchCase::CaseSensitive))")
    w("\t\t\tBest = Row;")
    w("\t}")
    w("\tNoteLookup(FMath::Max(Visited, 1));")
    w("\tif (Best == MAX_int32) return false;")
    w("\tOut = Rows[Best].Type;")
    w("\treturn true;")
    w("}")
    w("")
    w("bool ElementTypeForChildTag(ElementType Parent, FStringView Tag,")
    w("\tElementType& OutChild, int32& OutSlot)")
    w("{")
    w("\tint32 Count = 0;")
    w("\tconst FChildRow* Rows = ChildRows(Count);")
    w("\tint32 Best = MAX_int32;")
    w("\tint32 Visited = 0;")
    w("\tfor (auto It = Index().ByParentTagHash.CreateConstKeyIterator(")
    w("\t\t\tTagKey(Parent, GetTypeHash(Tag))); It; ++It)")
    w("\t{")
    w("\t\t++Visited;")
    w("\t\tconst int32 Row = It.Value();")
    w("\t\tif (Row >= Best || Rows[Row].Parent != Parent) continue;")
    w("\t\tif (Tag.Equals(FStringView(Rows[Row].Tag), ESearchCase::CaseSensitive))")
    w("\t\t\tBest = Row;")
    w("\t}")
    w("\tNoteLookup(FMath::Max(Visited, 1));")
    w("\tif (Best == MAX_int32) return false;")
    w("\tOutChild = Rows[Best].Child;")
    w("\tOutSlot = Rows[Best].Slot;")
    w("\treturn true;")
    w("}")
    w("")
    w("const TCHAR* ChildTagFor(ElementType Parent, ElementType Child)")
    w("{")
    w("\tNoteLookup(1);")
    w("\tconst int32* Row = Index().ByParentChild.Find(PairKey(Parent, Child));")
    w("\tif (Row == nullptr) return TagForElement(Child);")
    w("\tint32 Count = 0;")
    w("\treturn ChildRows(Count)[*Row].Tag;")
    w("}")
    w("")
    w("int32 SlotFor(ElementType Parent, ElementType Child)")
    w("{")
    w("\tNoteLookup(1);")
    w("\tconst int32* Row = Index().ByParentChild.Find(PairKey(Parent, Child));")
    w("\tif (Row == nullptr) return -1;")
    w("\tint32 Count = 0;")
    w("\treturn ChildRows(Count)[*Row].Slot;")
    w("}")
    w("")
    w("void ForEachAdmissibleChild(ElementType Parent,")
    w("\tTFunctionRef<void(int32 Slot, ElementType Child)> Fn)")
    w("{")
    w("\t// An enumeration rather than a lookup: it visits the parent's own rows,")
    w("\t// which the index locates, instead of the whole table.")
    w("\tconst TPair<int32, int32>* Span = Index().SpanByParent.Find(static_cast<int32>(Parent));")
    w("\tif (Span == nullptr) { NoteLookup(1); return; }")
    w("\tNoteLookup(Span->Value - Span->Key);")
    w("\tint32 Count = 0;")
    w("\tconst FChildRow* Rows = ChildRows(Count);")
    w("\tfor (int32 I = Span->Key; I < Span->Value; ++I)")
    w("\t\tif (Rows[I].Parent == Parent) Fn(Rows[I].Slot, Rows[I].Child);")
    w("}")
    w("")
    w("TArray<FString> RefNameOptions(const UMjNodeComponent* Node, int32 FieldId)")
    w("{")
    w("\tTArray<FString> Out;")
    w("\tif (Node == nullptr) return Out;")
    w("\tElementType Self;")
    w("\tif (!ElementTypeOfNode(*Node, Self)) return Out;")
    w("\tconst std::vector<ElementType> Targets =")
    w("\t\tps::sdk::detail::RefTargetsAt(Self, FieldId);")
    w("\tif (Targets.empty()) return Out;")
    w("\tconst USceneComponent* Root = Node;")
    w("\twhile (Root->GetAttachParent() != nullptr) Root = Root->GetAttachParent();")
    w("\tCollectNames(Root, Targets, Out);")
    w("\tOut.Sort();")
    w("\treturn Out;")
    w("}")
    w("")
    w("}  // namespace ps::ue")
    return "\n".join(o) + "\n"



def urlab_root(explicit: str | None = None) -> str | None:
    """The URLab checkout to emit into, or None with the reason printed by the
    caller. ProtoSpec is usable without URLab, so an absent root is a skip."""
    raw = explicit or os.environ.get(ENV_ROOT)
    if not raw:
        return None
    root = os.path.abspath(os.path.expanduser(raw))
    if not os.path.isdir(os.path.join(root, "Source", "URLab")):
        raise UeError(f"{root} is not a URLab checkout (no Source/URLab)")
    return root


def run(check: bool, out: str | None = None,
        prefix: str = DEFAULT_PREFIX) -> list[str]:
    """Write or verify the UE profile. Returns the stale paths under --check."""
    root = urlab_root(out)
    if root is None:
        print(f"UE profile skipped: no URLab checkout (set ${ENV_ROOT} or "
              "pass --out)")
        return []
    files = generate(prefix=prefix)
    if check:
        stale = []
        for name, content in sorted(files.items()):
            path = os.path.join(root, name)
            if not os.path.exists(path):
                stale.append(f"{name} (missing)")
                continue
            with open(path, "r", encoding="utf-8", newline="") as fh:
                current = fh.read()
            if current.replace("\r\n", "\n") != content:
                stale.append(name)
        if not stale:
            print(f"{root}: UE profile is up to date ({len(files)} files)")
        return stale

    written = 0
    for name, content in sorted(files.items()):
        path = os.path.join(root, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        written += 1
    print(f"wrote {written} UE profile files to {root}")
    return []


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", help=f"URLab checkout root (else ${ENV_ROOT})")
    ap.add_argument("--check", action="store_true",
                    help="verify the checked-in tree is up to date, do not write")
    ap.add_argument("--prefix", default=DEFAULT_PREFIX,
                    help="reflected-type name prefix for every generated type")
    args = ap.parse_args()

    stale = run(check=args.check, out=args.out, prefix=args.prefix)
    if stale:
        sys.stderr.write(
            "the UE profile is out of date; re-run "
            "`Scripts/regen_ue_profile.ps1` (or .sh):\n  "
            + "\n  ".join(stale) + "\n")
        sys.exit(1)


if __name__ == "__main__":
    main()

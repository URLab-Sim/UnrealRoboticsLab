    w("// UE storage without naming any of it. The load-bearing part is the fixed")
    w("// adapter: transfer is WHOLE-ARRAY in MJCF component order, never indexed,")
    w("// because FMjQuatRot has no operator[]. Code that indexed a fixed value")
    w("// generically would compile for FVector and read a quaternion off by a slot.")
    w("//")
    w("// A range-arity attribute and an unbounded one share TArray storage, so")
    w("// their bounds cannot be recovered from the type. The reader enforces them")
    w("// from the binding table's arity instead (mjcf_reader.inc, ReadVector).")

    w("")
    w("#include <cstddef>")
    w("#include <string>")
    w("#include <string_view>")
    w("#include <type_traits>")
    w("#include <utility>")
    w("")
    w('#include "CoreMinimal.h"')
    w('#include "Containers/StringConv.h"')
    w('#include "Containers/StringView.h"')
    w("")
    w('#include "MuJoCo/Spec/MjFrameTypes.h"')
    w('#include "MuJoCo/Spec/MjRefView.h"')
    w('#include "MuJoCo/Gen/MjKeywords.gen.h"')
    w('#include "protospec/profile.h"')
    w("")
    w("namespace ps::ue")
    w("{")
    w("namespace sdk = ps::sdk;")
    w("")
    w("// --- Str ---------------------------------------------------------- //")
    w("struct FMjStrPolicy")
    w("{")
    w("\tusing string = FString;")
    w("\tusing view = FStringView;")
    w("")
    w("\tstatic view View(const string& S) { return view(S); }")
    w("")
    w("\tstatic string FromUtf8(std::string_view U)")
    w("\t{")
    w("\t\tFUTF8ToTCHAR Conv(U.data(), static_cast<int32>(U.size()));")
    w("\t\treturn FString::ConstructFromPtrSize(Conv.Get(), Conv.Length());")
    w("\t}")
    w("")
    w("\tstatic std::string ToUtf8(view V)")
    w("\t{")
    w("\t\tFTCHARToUTF8 Conv(V.GetData(), V.Len());")
    w("\t\treturn std::string(Conv.Get(), static_cast<std::size_t>(Conv.Length()));")
    w("\t}")
    w("")
    w("\tstatic bool Equals(view A, view B)")
    w("\t{ return A.Equals(B, ESearchCase::CaseSensitive); }")
    w("")
    w("\tstatic bool EqualsUtf8(view A, std::string_view B)")
    w("\t{ return ToUtf8(A) == B; }")
    w("")
    w("\tstatic bool Empty(view V) { return V.IsEmpty(); }")
    w("")
    w("\tstatic bool StartsWith(view V, std::string_view P)")
    w("\t{")
    w("\t\tconst string Pattern = FromUtf8(P);")
    w("\t\treturn V.StartsWith(view(Pattern), ESearchCase::CaseSensitive);")
    w("\t}")
    w("")
    w("\tstatic string Concat(view A, view B) { return string(A) + string(B); }")
    w("")
    w("\t// Case-insensitive, as every FString hash in the engine is. Equal keys")
    w("\t// still hash equal, which is all a name index needs.")
    w("\tstatic std::size_t Hash(view V)")
    w("\t{ return static_cast<std::size_t>(GetTypeHash(V)); }")
    w("};")
    w("")
    w("// --- Shape -------------------------------------------------------- //")
    w("// The value a reference slot reads as: a name, distinguishable at compile")
    w("// time from a plain string attribute, and default-constructible so the")
    w("// reader can build one before authoring it.")
    w("struct FMjRefName")
    w("{")
    w("\tFString Name;")
    w("};")
    w("")
    w("namespace storage")
    w("{")
    w("template <class T> struct TIsOptional : std::false_type { using Inner = T; };")
    w("template <class T> struct TIsOptional<TOptional<T>> : std::true_type")
    w("{ using Inner = T; };")
    w("")
    w("// The reference-view trait is RefView's own (MjRefView.h) rather than a")
    w("// second copy: a trait kept in step by hand with a type it does not own")
    w("// is a drift source, and this one would fail silently, by classifying")
    w("// every reference as a plain string attribute.")
    w("using urlab::ref_view_detail::TIsRefView;")
    w("")
    w("template <class T> struct TIsArray : std::false_type {};")
    w("template <class T> struct TIsArray<TArray<T>> : std::true_type")
    w("{ using Element = T; };")
    w("")
    w("template <class T> struct TInnerOf { using Type = T; };")
    w("template <class T> struct TInnerOf<TOptional<T>> { using Type = T; };")
    w("template <class A, class B> struct TInnerOf<urlab::RefView<A, B>>")
    w("{ using Type = FMjRefName; };")
    w("")
    w("template <class I>")
    w("constexpr sdk::Shape KindOf()")
    w("{")
    w("\tif constexpr (std::is_same_v<I, FMjRefName>) { return sdk::Shape::Ref; }")
    w("\telse if constexpr (std::is_same_v<I, FString>) { return sdk::Shape::Str; }")
    w("\telse if constexpr (std::is_same_v<I, bool>) { return sdk::Shape::Bool; }")
    w("\telse if constexpr (std::is_enum_v<I>) { return sdk::Shape::Enum; }")
    w("\telse if constexpr (")
    for i, t in enumerate(FIXED_TYPES):
        tail = ")" if i == len(FIXED_TYPES) - 1 else " ||"
        w(f"\t\tstd::is_same_v<I, {t}>{tail}")

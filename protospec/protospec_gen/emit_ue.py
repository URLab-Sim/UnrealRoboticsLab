"""ProtoSpec Unreal emitter: schema AST -> the UE emission profile.

The third profile. It consumes the same AST :mod:`protospec_gen.frontend` builds
from upstream's ``src/xml/mjcf.schema`` and emits, into a URLab checkout, the
half of the UE spec model that scales with the schema:

    Public/MuJoCo/Gen/
      MjEnums.gen.h          one UENUM per schema enum, keywords as UMETA names
      MjKeywords.gen.h       enum <-> MJCF keyword declarations
      Elements/Mj<El>.gen.h  one UCLASS per schema element: UPROPERTYs + the
                             Get/Set/Has/Clear accessor quartet per attribute
      MjElements.gen.h       umbrella include + reference-target phantoms
      MjVisit.gen.h          the generated Visit hook the SDK and io consume
      MjStorage.gen.h        the Str and Shape policies over UE storage
      MjDefaults.gen.h       ApplyDefault declarations + the defaults prototype
      MjDispatch.gen.h       per-element dispatch: class <-> ElementType, child
                             storage slots, contextual XML tag recovery
      MjReflect.gen.h        per-element presence/clear thunks over TOptional
      MjProfile.gen.h        the generated half of the profile tag type
    Private/MuJoCo/Gen/
      MjKeywords.gen.cpp  MjDefaults.gen.cpp  MjDispatch.gen.cpp
      MjReflect.gen.cpp   MjCoverage.gen.cpp (generated schema-coverage test)

Storage mapping:

===========================  ==========================================
schema                       UE
===========================  ==========================================
optional attribute           ``TOptional<T>`` UPROPERTY, EditAnywhere only
``required`` attribute       plain ``T``
``string`` / ``file``        ``FString``
``ref<ns>``                  ``FString`` slot, handed to Visit as ``RefView``
position ``double[3]``       ``FMjPosition3``
direction ``double[3]``      ``FMjDirection3``
every other ``double[3]``    ``FMjVec3`` (no conversion is ever right)
``double[2]``                ``FVector2D``
orientation ``double[4]``    ``FMjQuatRot`` (verbatim MJCF [w,x,y,z])
``float[4]``                 ``FLinearColor``
every other array            ``TArray<T>``
``enum`` / ``flags``         ``UENUM`` / ``TArray<UENUM>``
child lists                  nothing: the attachment hierarchy is the list
identity ``name``            ``UMjNodeComponent::MjName``
===========================  ==========================================

Hard emitter rules, none of which UHT catches:

* a ``TOptional`` UPROPERTY is ``EditAnywhere`` only -- never
  ``BlueprintReadWrite``/``BlueprintReadOnly`` (UHT accepts them and emits a
  ``bad_type`` Blueprint pin) and never ``Replicated`` (hard UHT error). The
  quartet is what Blueprint uses. Enforced by :func:`lint`.
* accessor-quartet parameters are plain inner types, never ``TOptional``, and
  carry no default values. Enforced by :func:`lint`.
* fixed-arity access is whole-array transfer through the ``Shape::fixed``
  adapter, never per-index: none of the frame types has an ``operator[]``, so
  an indexing assumption would compile for ``FVector`` and read a quaternion's
  components off by a slot. A quaternion default is written by named
  component for the same reason. Enforced by :func:`lint`.

The hand seams this output binds to, and nothing else: ``UMjNodeComponent``
(base class, public ``TOptional<FString> MjName``),
``urlab::RefView<Target, SlotType>`` (see MjVisit.gen.h's header comment for the
exact contract) and the frame types in ``MuJoCo/Spec/MjFrameTypes.h``:
``FMjQuatRot`` (four verbatim doubles named W, X, Y, Z, constructible in that
order) and ``FMjPosition3`` / ``FMjDirection3`` / ``FMjVec3`` (three verbatim
doubles named X, Y, Z, constructible in that order).

Entry point: ``python -m protospec_gen.emit_ue --out <URLab>`` writes the tree;
``--check`` regenerates in memory and fails on any byte difference. The URLab
root comes from ``--out``, else ``$PROTOSPEC_URLAB_ROOT``; with neither, the
profile is skipped with a stated reason so the fork's own gates still run.
"""


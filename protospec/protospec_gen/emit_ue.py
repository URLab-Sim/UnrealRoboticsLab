def emit_reflect_cpp(s: UeSchema) -> str:
    o: list[str] = []
    w = o.append
    w(LICENSE.rstrip("\n"))
    w("")
    w(BANNER)
    w("")
    w('#include "MuJoCo/Gen/MjReflect.gen.h"')
    w('#include "MuJoCo/Spec/MjFieldText.h"')
    w("")
    w("namespace ps::ue")
    w("{")
    w("namespace")
    w("{")
    for e in s.elements:
        cls = s.cls[e["name"]]
        name = e["name"]
        w("")
        w(f"const FMjFieldSpec Fields_{name}[] = {{")
        if not e["fields"]:
            w("\t{ nullptr, nullptr, nullptr, nullptr, EMjFieldKind::String, 0, 0, false, false },")
        for f in e["fields"]:
            file_resource = "true" if f.get("annotations", {}).get("file") else "false"
            text = "true" if f.get("annotations", {}).get("element_text") else "false"
            t = f["type"]
            kind = t["kind"]
            if kind == "prim":
                field_kind = {"bool": "Bool", "int32": "Int32", "uint64": "Uint64",
                              "float": "Float", "double": "Double", "string": "String"}[t["prim"]]
                type_name = t["prim"]
            elif kind == "ref":
                field_kind, type_name = "Ref", t["target"]
            else:
                field_kind, type_name = "Enum", t["name"]
            arity = t.get("arity", {})
            if arity.get("kind") == "fixed":
                amin = amax = arity["size"]
            elif arity.get("kind") == "range":
                amin, amax = arity["min"], arity["max"]
            else:
                amin = amax = 0
            member = "MjName" if UeSchema.is_identity(f) else s.member(e, f)
            target_from = f.get("annotations", {}).get("target_from", "")
            w(f"\t{{ TEXT(\"{cpp_str(f['xml'])}\"), TEXT(\"{cpp_str(member)}\"), "
              f"TEXT(\"{cpp_str(type_name)}\"), TEXT(\"{cpp_str(target_from)}\"), "
              f"EMjFieldKind::{field_kind}, {amin}, {amax}, {file_resource}, {text} }},")
        w("};")
        w("")
        w(f"bool Has_{name}(const void* P, int FieldId)")
        w("{")
        w(f"\tconst {cls}& E = *static_cast<const {cls}*>(P);")
        w("\tswitch (FieldId)")
        w("\t{")
        for fid, f in enumerate(e["fields"]):
            member = "MjName" if UeSchema.is_identity(f) else s.member(e, f)
            expression = f"E.{member}.IsSet()" if f["optional"] or UeSchema.is_identity(f) else "true"
            w(f"\tcase {fid}: return {expression};")
        w("\tdefault: return false;")
        w("\t}")
        w("}")
        w("")
        w(f"bool Parse_{name}(void* P, int FieldId, FStringView Text)")
        w("{")
        w(f"\t{cls}& E = *static_cast<{cls}*>(P);")
        w("\tswitch (FieldId)")
        w("\t{")
        for fid, f in enumerate(e["fields"]):
            vt = value_type(s, f)
            member = "MjName" if UeSchema.is_identity(f) else s.member(e, f)
            arity = f["type"].get("arity", {})
            if arity.get("kind") == "fixed":
                mn = mx = arity["size"]
            elif arity.get("kind") == "range":
                mn, mx = arity["min"], arity["max"]
            elif arity.get("kind") == "unbounded":
                mn, mx = 1, -1
            else:
                mn = mx = 1
            w(f"\tcase {fid}: {{ {vt} Value{{}};")
            w(f"\t\tif (!urlab::spec::fieldtext::Parse(Text, Value, {mn}, {mx})) return false;")
            w(f"\t\tE.{member} = MoveTemp(Value); return true; }}")
        w("\tdefault: return false;")
        w("\t}")
        w("}")
        w("")
        w(f"bool Format_{name}(const void* P, int FieldId, FString& Out)")
        w("{")
        w(f"\tconst {cls}& E = *static_cast<const {cls}*>(P);")
        w("\tswitch (FieldId)")
        w("\t{")
        for fid, f in enumerate(e["fields"]):
            member = "MjName" if UeSchema.is_identity(f) else s.member(e, f)
            if f["optional"] or UeSchema.is_identity(f):
                w(f"\tcase {fid}: if (!E.{member}.IsSet()) return false;")
                w(f"\t\tOut = urlab::spec::fieldtext::Format(E.{member}.GetValue()); return true;")
            else:
                w(f"\tcase {fid}: Out = urlab::spec::fieldtext::Format(E.{member}); return true;")
        w("\tdefault: return false;")
        w("\t}")
        w("}")
        w("")
        clearable = [(fid, f) for fid, f in enumerate(e["fields"])
                     if f["optional"]]
        w(f"void Clear_{name}(void* P, int FieldId)")
        w("{")
        if not clearable:
            w("\t(void)P; (void)FieldId;")
        else:
            w(f"\t{cls}& E = *static_cast<{cls}*>(P);")
            w("\tswitch (FieldId)")
            w("\t{")
            for fid, f in clearable:
                if UeSchema.is_identity(f):
                    w(f"\tcase {fid}: E.MjName.Reset(); break;")
                else:
                    w(f"\tcase {fid}: E.{s.member(e, f)}.Reset(); break;")
            w("\tdefault: break;")
            w("\t}")
        w("}")
    w("")
    w("bool Has_None(const void*, int) { return false; }")
    w("void Clear_None(void*, int) {}")
    w("bool Parse_None(void*, int, FStringView) { return false; }")
    w("bool Format_None(const void*, int, FString&) { return false; }")
    w("")
    w("struct FThunkRow")
    w("{")
    w("\tElementType Type;")
    w("\tFMjElementThunks Thunks;")
    w("};")
    w("")
    w("const FThunkRow Rows[] = {")
    for e in s.elements:
        name = e["name"]
        w(f"\t{{ ElementType::{name}, {{ &Has_{name}, &Clear_{name}, &Parse_{name}, &Format_{name},")
        # worldbody is schema alias=body too, but the native Body() branch
        # rejects any attributes there. The frontend gates the alias set.
        ignores_unknown = bool(e.get('alias')) and e['xml'] != 'worldbody'
        w(f"\t\tFields_{name}, {len(e['fields'])}, {'true' if ignores_unknown else 'false'} }} }},")
    w("};")
    w("")
    w("const FMjElementThunks NoThunks{ &Has_None, &Clear_None, &Parse_None, &Format_None, nullptr, 0, false };")
    w("")
    w("}  // namespace")
    w("")
    w("const FMjElementThunks& Thunks(ElementType Type)")
    w("{")
    w("\tfor (const FThunkRow& Row : Rows)")
    w("\t\tif (Row.Type == Type) return Row.Thunks;")
    w("\treturn NoThunks;")
    w("}")
    w("")
    w("}  // namespace ps::ue")
    return "\n".join(o) + "\n"



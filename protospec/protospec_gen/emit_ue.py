def generate(root: str | None = None,
             prefix: str = DEFAULT_PREFIX) -> dict[str, str]:
    """{URLab-relative path: content} for every file the UE profile owns."""
    s = UeSchema(load_schema(root), prefix)
    files: dict[str, str] = {}
    for e in s.elements:
        fam = element_family(s, e["name"])
        sub = f"{fam}/" if fam else ""
        files[f"{PUBLIC}/Elements/{sub}Mj{e['name']}.gen.h"] = element_header(s, e)
    files[f"{PUBLIC}/MjElements.gen.h"] = emit_elements_umbrella(s)
    files[f"{PUBLIC}/MjEnums.gen.h"] = emit_enums(s)
    files[f"{PUBLIC}/MjKeywords.gen.h"] = emit_keywords_h(s)
    files[f"{PUBLIC}/MjVisit.gen.h"] = emit_visit(s)
    files[f"{PUBLIC}/MjStorage.gen.h"] = emit_storage(s)
    files[f"{PUBLIC}/MjDefaults.gen.h"] = emit_defaults_h(s)
    files[f"{PUBLIC}/MjDispatch.gen.h"] = emit_dispatch_h(s)
    files[f"{PUBLIC}/MjReflect.gen.h"] = emit_reflect_h(s)
    files[f"{PUBLIC}/MjProfile.gen.h"] = emit_profile(s)
    write = SpecWritePlan(s)
    files[f"{PUBLIC}/MjSpecWrite.gen.h"] = emit_specwrite_h(s, write)
    files[f"{PRIVATE}/MjSpecWrite.gen.cpp"] = emit_specwrite_cpp(s, write)
    files[f"{PRIVATE}/MjKeywords.gen.cpp"] = emit_keywords_cpp(s)
    files[f"{PRIVATE}/MjDefaults.gen.cpp"] = emit_defaults_cpp(s)
    files[f"{PRIVATE}/MjDispatch.gen.cpp"] = emit_dispatch_cpp(s)
    files[f"{PRIVATE}/MjReflect.gen.cpp"] = emit_reflect_cpp(s)
    files[f"{TESTS}/MjGenCoverage.gen.cpp"] = emit_coverage(s)
    files["Scripts/regen_ue_profile.ps1"] = emit_regen_ps1()
    files["Scripts/regen_ue_profile.sh"] = emit_regen_sh()
    coverage(s, files)
    lint(files)
    return files


def coverage(s: UeSchema, files: dict[str, str]) -> None:
    """Every element has a class, every attribute a property, every enum a
    UENUM -- read off the schema and checked against the emitted text, so a
    silently dropped element or attribute fails generation rather than the
    build."""
    missing: list[str] = []
    for e in s.elements:
        fam = element_family(s, e["name"])
        sub = f"{fam}/" if fam else ""
        path = f"{PUBLIC}/Elements/{sub}Mj{e['name']}.gen.h"
        text = files.get(path)
        if text is None:
            missing.append(f"element {e['name']}: no header")
            continue
        if f"class URLAB_API {s.cls[e['name']]} :" not in text:
            missing.append(f"element {e['name']}: no UCLASS")
        for _fid, f in s.stored_fields(e):
            member = s.member(e, f)
            if not re.search(rf"^\t{re.escape(stored_type(s, f))} "
                             rf"{re.escape(member)};$", text, re.M):
                missing.append(f"{e['name']}.{f['name']}: no UPROPERTY")
            for verb in ("Get", "Set", "Has"):
                if f"\t{verb}{member}(" not in text.replace("bool ", "\t") and \
                        f"{verb}{member}(" not in text:
                    missing.append(f"{e['name']}.{f['name']}: no {verb}")
        if f"void Visit({s.cls[e['name']]}& Element" not in \
                files[f"{PUBLIC}/MjVisit.gen.h"]:
            missing.append(f"element {e['name']}: no Visit")
        if f"void ApplyDefault({s.cls[e['name']]}& Element)" not in \
                files[f"{PRIVATE}/MjDefaults.gen.cpp"]:
            missing.append(f"element {e['name']}: no ApplyDefault")
    enums_text = files[f"{PUBLIC}/MjEnums.gen.h"]
    for en in s.enums:
        if f"enum class {s.enum[en['name']]} : uint8" not in enums_text:
            missing.append(f"enum {en['name']}: no UENUM")
        for m in en["members"]:
            if f"\t{ident(m['name'])} UMETA" not in enums_text:
                missing.append(f"enum {en['name']}.{m['name']}: no enumerator")
    if missing:
        raise UeError("the emitted profile does not cover the schema:\n  " +
                      "\n  ".join(missing[:40]))


_BP_ON_OPTIONAL = re.compile(
    r"UPROPERTY\([^)]*Blueprint[^)]*\)\s*\n\s*TOptional<")
_REPLICATED = re.compile(r"UPROPERTY\([^)]*Replicated[^)]*\)")
_OPTIONAL_PARAM = re.compile(r"\b(?:Get|Set|Has|Clear)\w+\([^)]*TOptional<")
_DEFAULTED_PARAM = re.compile(r"\b(?:Get|Set|Has|Clear)\w+\([^)]*=[^)]*\)\s*\{")
# FVector joins the storage types here even though nothing stores in it: it is
# the one whose indexed access would compile silently, so it stays rejected.
_INDEXED_FIXED = re.compile(r"\b(?:FVector|" + "|".join(FIXED_TYPES) + r")\s*"
                            r"\w*\s*\[\s*\d")


def lint(files: dict[str, str]) -> None:
    """The hard emitter rules, asserted on the emitted text.

    Each of these is a mistake UHT accepts: a Blueprint specifier on a TOptional
    ships a broken bad_type pin, Replicated is rejected only for some inners, a
    TOptional accessor parameter cannot take a default, and indexed access to a
    fixed-arity value compiles for FVector while transposing every quaternion.
    """
    bad: list[str] = []
    for path, text in files.items():
        if not path.endswith((".h", ".cpp")):
            continue
        if _BP_ON_OPTIONAL.search(text):
            bad.append(f"{path}: a Blueprint specifier on a TOptional UPROPERTY")
        if "Blueprint" in text and "UPROPERTY" in text:
            for line in text.splitlines():
                if line.lstrip().startswith("UPROPERTY(") and \
                        "Blueprint" in line:
                    bad.append(f"{path}: Blueprint specifier on {line.strip()}")
        if _REPLICATED.search(text):
            bad.append(f"{path}: a Replicated UPROPERTY")
        if _OPTIONAL_PARAM.search(text):
            bad.append(f"{path}: a TOptional accessor parameter")
        if _DEFAULTED_PARAM.search(text):
            bad.append(f"{path}: an accessor parameter with a default value")
        if _INDEXED_FIXED.search(text):
            bad.append(f"{path}: indexed access to a fixed-arity vector type")
        if not text.isascii():
            bad.append(f"{path}: non-ASCII bytes (MSVC decodes a BOM-less file "
                       "in the system codepage)")
    if bad:
        raise UeError("generated output violates a hard emitter rule:\n  " +
                      "\n  ".join(sorted(set(bad))))



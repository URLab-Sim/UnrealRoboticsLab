    w("// none of it is a hand-written switch.")
    w("//")
    w("// ChildSlots is the contract the tree adapters implement ForEachChildSlot")
    w("// against: it enumerates, per element type, the storage slots it admits")
    w("// and the concrete class each slot accepts. The slot number is the schema")
    w("// child index, so the writer recovers the contextual tag from the shared")
    w("// binding table and the reader groups its child pass by it.")

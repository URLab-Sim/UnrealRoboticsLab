def element_header(s: UeSchema, elem: dict) -> str:
    o: list[str] = []
    w = o.append
    name = elem["name"]
    cls = s.cls[name]
    w(LICENSE.rstrip("\n"))
    w("")
    w(BANNER)
    w("//")
    w(f"// <{elem['xml']}>: {len(elem['fields'])} schema attributes, of which "
      f"{len(s.stored_fields(elem))} carry storage here")
    w("// (the identity attribute lives on UMjNodeComponent::MjName).")
    w("#pragma once")
    w("")
    w('#include "CoreMinimal.h"')
    w('#include "MuJoCo/Spec/MjNodeComponent.h"')
    if _uses_frame_type(s, elem):
        w('#include "MuJoCo/Spec/MjFrameTypes.h"')
    if _uses_enum(s, elem):
        w('#include "MuJoCo/Gen/MjEnums.gen.h"')
    w("")
    w(f'#include "Mj{name}.gen.generated.h"')
    w("")
    if elem.get("alias"):
        w(f"// The schema aliases <{elem['xml']}> onto <{elem['alias']}>, so it")
        w("// admits that element's children.")
    if s.is_hand_base(name):
        # URLab subclasses this element by hand, and the subclass is what a
        # scene holds, so it -- not this -- is the one the picker offers.
        w(f"// URLab derives UMj{name} from this and places that; the schema")
        w("// attributes are here and the hand behaviour is there.")
        w("UCLASS(ClassGroup = (MuJoCo))")
    else:
        w("UCLASS(ClassGroup = (MuJoCo), meta = (BlueprintSpawnableComponent))")
    w(f"class URLAB_API {cls} : public UMjNodeComponent")
    w("{")
    w("\tGENERATED_BODY()")
    w("")
    w("public:")

    category = name
    for fid, f in s.stored_fields(elem):
        vt = value_type(s, f)
        st = stored_type(s, f)
        member = s.member(elem, f)
        documentation = _field_doc(s, elem, f)
        for line in doc_comment(documentation, "\t"):
            w(line)
        meta = [f'ToolTip = "{cpp_str(documentation)}"']
        meta.extend(_clamp_meta(f))
        if f["type"]["kind"] == "ref":
            meta.append(f'GetOptions = "Get{member}Options"')
        b_derived_model_file = name == "ModelAsset" and f["xml"] == "file"
        spec = f'{"VisibleAnywhere" if b_derived_model_file else "EditAnywhere"}, Category = "{_ue_category(category, f)}"'
        if b_derived_model_file:
            meta.extend(['EditCondition = "false"', "EditConditionHides"])
        if f["xml"] in overlay_ue.UE_ADVANCED:
            spec += ", AdvancedDisplay"
        spec += f", meta = ({', '.join(meta)})"
        w(f"\tUPROPERTY({spec})")
        w(f"\t{st} {member};")
        w("")

    w("\t// --- Blueprint access ---")
    w("\t// TOptional has no Blueprint pin, so presence and value reach")
    w("\t// Blueprint through this quartet. Get() falls back to the schema")
    w("\t// default; it does NOT resolve the default-class chain, which is")
    w("\t// EffectiveField's job.")
    for fid, f in s.stored_fields(elem):
        vt = value_type(s, f)
        member = s.member(elem, f)
        pt = param_type(vt)
        # Flat, and the same category the properties use: see `_ue_category`.
        cat = "MuJoCo"
        w(f'\tUFUNCTION(BlueprintPure, Category = "{cat}")')
        if f["optional"]:
            w(f"\tbool Has{member}() const {{ return {member}.IsSet(); }}")
        else:
            w(f"\tbool Has{member}() const {{ return true; }}")
        w("")
        w(f'\tUFUNCTION(BlueprintPure, Category = "{cat}")')
        if f["optional"]:
            w(f"\t{vt} Get{member}() const "
              f"{{ return {member}.Get({get_fallback(s, f)}); }}")
        else:
            w(f"\t{vt} Get{member}() const {{ return {member}; }}")
        w("")
        w(f'\tUFUNCTION(BlueprintCallable, Category = "{cat}")')
        w(f"\tvoid Set{member}({pt} InValue) {{ {member} = InValue; }}")
        w("")
        if f["optional"]:
            w(f'\tUFUNCTION(BlueprintCallable, Category = "{cat}")')
            w(f"\tvoid Clear{member}() {{ {member}.Reset(); }}")
            w("")
        if f["type"]["kind"] == "ref":
            w("\tUFUNCTION()")
            w(f"\tTArray<FString> Get{member}Options() const")
            w(f"\t{{ return RefNameOptions({fid}); }}")
            w("")
    w("};")
    return "\n".join(o) + "\n"


def _field_doc(s: UeSchema, elem: dict, f: dict) -> str:
    """What the editor tells a user about one attribute.

    MuJoCo's reference manual first, the schema's own `doc` where the manual has
    nothing, and the wire name always: an attribute a user reads about in the
    manual has to be findable in the panel by the name the manual calls it.
    """
    doc = s.tooltip.get(f"{elem['schema_name']}.{f['xml']}") or f.get("doc", "")
    return f"{doc} (MJCF: {f['xml']})" if doc else f"MJCF: {f['xml']}"


def _facet_number(f: dict, value) -> str:
    """A range facet as a UE clamp value, integral where the field is."""
    t = f["type"]
    if t["kind"] == "prim" and t["prim"] == "int32":
        return str(int(value))
    text = repr(float(value))
    return text[:-2] if text.endswith(".0") else text


def _clamp_meta(f: dict) -> list[str]:
    """The schema's numeric range as details-panel clamps.

    `positive` becomes `ClampMin = "0"` and is the one inexact translation here:
    UE's clamp is inclusive and MJCF's facet is not, so zero gets through the
    panel and is refused by MuJoCo's compiler, which is the authority either
    way. The alternative -- no bound at all -- lets a user type a negative
    stiffness and find out at compile.
    """
    annotations = f.get("annotations", {})
    out = []
    if "min" in annotations:
        out.append(f'ClampMin = "{_facet_number(f, annotations["min"])}"')
    elif annotations.get("positive"):
        out.append('ClampMin = "0"')
    if "max" in annotations:
        out.append(f'ClampMax = "{_facet_number(f, annotations["max"])}"')
    return out


def _ue_category(element: str, f: dict) -> str:
    """The details-panel category an attribute is filed under: `MuJoCo`, flat.

    One category per element, no sub-groups, and the element's own name left
    out of it.

    The name is redundant: the panel is showing one component and that component
    already says which element it is, so `MuJoCo|Geom` on a geom tells the user
    what they just selected.

    The sub-groups are worse than redundant. Unreal reads `A|B|C` as a nested
    path, so filing some of an element's attributes under `MuJoCo|Position` and
    the rest under `MuJoCo|Position|Transmission` made the child create the
    parent implicitly and early while the parent's own rows arrived later in a
    second section. The panel drew the element twice, and only one of the two
    carried the inherited-value rows -- which is invisible to every test, since
    both sections are correctly built and the split is in how the view groups
    them. Sixty-six generated classes had it.

    Grouping can come back, but it has to be a shape that cannot produce a
    parent and a child for the same element: everything one level down, or
    nothing.
    """
    return "MuJoCo"



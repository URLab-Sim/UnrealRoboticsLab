def emit_cpp(data: dict, digest: str) -> str:
    L: list[str] = []
    a = L.append
    a("// " + BANNER)
    a("//")
    a("// The shared vocabulary of the UE <-> Python wire. Include this instead of")
    a("// typing string literals; a literal is how the two sides drift apart.")
    a("#pragma once")
    a("")
    a('#include "CoreMinimal.h"')
    a("")
    a("namespace URLabWire")
    a("{")
    a(f'inline const TCHAR* SchemaSha256 = TEXT("{digest}");')
    a("")

    a("// --- ops -----------------------------------------------------------------")
    a("namespace Op")
    a("{")
    for name, op in sorted(data["ops"].items()):
        a(f'\tinline const TCHAR* {"".join(w.capitalize() for w in name.split("_"))} = TEXT("{op}");')
    a("}")
    a("")

    a("// --- enum tokens ---------------------------------------------------------")
    for name, tokens in sorted(data["enums"].items()):
        ns = "".join(w.capitalize() for w in name.split("_"))
        a(f"namespace {ns}")
        a("{")
        for t in tokens:
            a(f'\tinline const TCHAR* {"".join(w.capitalize() for w in str(t).split("_"))} = TEXT("{t}");')
        a("}")
    a("")

    a("// --- capability model, split by kind --------------------------------------")
    a("// service = an ingress you stand up; output = data you emit; permission =")
    a("// authority you grant peers; local = a convenience with no wire at all.")
    a("//")
    a("// One table, in schema order, because EMjCapability indexes into it: the")
    a("// enum and the schema cannot fall out of step without the static_assert in")
    a("// MjCapabilities.h failing to build.")
    a("namespace Capability")
    a("{")
    a("enum class EKind : uint8 { Service, Output, Permission, Local };")
    a("struct FEntry")
    a("{")
    a("\tconst TCHAR* Name;   // the one spelling: enum, CLI token and log line")
    a("\tconst TCHAR* Cli;    // the -URLabCaps token")
    a("\tconst TCHAR* Wire;   // the advertised token, or nullptr for a local capability")
    a("\tEKind Kind;")
    a("};")
    a("inline const FEntry All[] = {")
    for e in data["caps"]:
        kind = {"service": "Service", "output": "Output",
                "permission": "Permission", "local": "Local"}[e["kind"]]
        wire = f'TEXT("{e["wire"]}")' if e.get("wire") else "nullptr"
        cli = f'TEXT("{e["cli"]}")' if e.get("cli") else "nullptr"
        a(f'\t{{TEXT("{e["name"]}"), {cli}, {wire}, EKind::{kind}}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['caps'])};")
    a("}")
    a("")

    permission_names = [e["name"] for e in data["cap_model"].get("permission", [])]
    a("// Exact permission vocabulary accepted by a protocol-v2 bootstrap.")
    a("// Generated from permission capability names, not wire aliases or callers.")
    a("namespace ProtocolV2Permission")
    a("{")
    a("inline const TCHAR* All[] = {")
    for name in permission_names:
        a(f'\tTEXT("{name}"),')
    a("};")
    a(f"inline constexpr int32 Count = {len(permission_names)};")
    a("}")
    a("")

    a("// --- op permissions -------------------------------------------------------")
    a("// The permission each op requires before the dispatcher will run it. An op")
    a("// absent from this table requires none, which is the DECLARED default rather")
    a("// than an omission: a hand-written check inside a handler is what this")
    a("// replaces, and a check that lives in a handler is one no caller can read.")
    a("namespace OpPermission")
    a("{")
    a("struct FEntry { const TCHAR* Op; const TCHAR* Permission; };")
    a("inline const FEntry All[] = {")
    for op, perm in sorted(data["op_perms"].items()):
        a(f'\t{{TEXT("{op}"), TEXT("{perm}")}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['op_perms'])};")
    a("}")
    a("")
    a("namespace OpAdapter")
    a("{")
    a("inline bool Allows(const FString& Op, const FString& Adapter)")
    a("{")
    for op, adapters in sorted(data["op_adapters"].items()):
        cond = " || ".join(f'Adapter == TEXT("{adapter}")' for adapter in adapters)
        a(f'\tif (Op == TEXT("{op}")) return {cond};')
    a("\treturn true; // legacy operations have not declared adapter restrictions yet")
    a("}")
    a("}")
    a("")
    a("namespace TypedRequest")
    a("{")
    a("struct FField { const TCHAR* Name; const TCHAR* Type; const TCHAR* LengthFrom; const TCHAR* Literal; bool Required; };")
    a("struct FShape { const TCHAR* Name; const FField* Fields; int32 Num; };")
    for shape_name, shape in data["request_shapes"].items():
        ident = "".join(word.capitalize() for word in shape_name.split("_"))
        fields = shape.get("fields") or {}
        if fields:
            a(f"inline const FField {ident}Fields[] = {{")
            for name, spec in fields.items():
                length = f'TEXT("{spec["length_from"]}")' if spec.get("length_from") else "nullptr"
                raw_literal = spec.get("value")
                literal_value = str(raw_literal).lower() if isinstance(raw_literal, bool) else raw_literal
                literal = f'TEXT("{literal_value}")' if raw_literal is not None else "nullptr"
                a(f'\t{{TEXT("{name}"), TEXT("{spec["type"]}"), {length}, {literal}, {str(spec["required"]).lower()}}},')
            a("};")
    a("inline const FShape All[] = {")
    for shape_name, shape in data["request_shapes"].items():
        ident = "".join(word.capitalize() for word in shape_name.split("_"))
        fields = shape.get("fields") or {}
        field_ptr = f"{ident}Fields" if fields else "nullptr"
        a(f'\t{{TEXT("{shape_name}"), {field_ptr}, {len(fields)}}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['request_shapes'])};")
    a("inline const FShape* Find(const FString& Name)")
    a("{")
    a("\tfor (const FShape& Shape : All) if (Name == Shape.Name) return &Shape;")
    a("\treturn nullptr;")
    a("}")
    request_variants = [
        (shape_name, shape["tagged"]["field"], tag, target)
        for shape_name, shape in data["request_shapes"].items()
        if "tagged" in shape
        for tag, target in shape["tagged"]["variants"].items()
    ]
    if request_variants:
        a("struct FTaggedVariant { const TCHAR* Union; const TCHAR* Field; const TCHAR* Tag; const TCHAR* Shape; };")
        a("inline const FTaggedVariant TaggedVariants[] = {")
        for union, field, tag, target in request_variants:
            a(f'\t{{TEXT("{union}"), TEXT("{field}"), TEXT("{tag}"), TEXT("{target}")}},')
        a("};")
        a(f"inline constexpr int32 TaggedVariantCount = {len(request_variants)};")
    a("}")
    a("")
    a("namespace TypedOp")
    a("{")
    a("struct FDecl { const TCHAR* Op; const TCHAR* RequestShape; const TCHAR* Service; const TCHAR* Permission; const TCHAR* Authority; const TCHAR* Execution; const TCHAR* const* Adapters; int32 NumAdapters; };")
    for op, metadata in sorted(data["typed_ops"].items()):
        ident = "".join(word.capitalize() for word in op.split("_"))
        adapters = metadata["adapters"]
        a(f"inline const TCHAR* const {ident}Adapters[] = {{")
        for adapter in adapters:
            a(f'\tTEXT("{adapter}"),')
        a("};")
    a("inline const FDecl All[] = {")
    for op, metadata in sorted(data["typed_ops"].items()):
        ident = "".join(word.capitalize() for word in op.split("_"))
        a(f'\t{{TEXT("{op}"), TEXT("{metadata["request_shape"]}"), TEXT("{metadata["service"]}"), TEXT("{metadata["permission"]}"), TEXT("{metadata["authority"]}"), TEXT("{metadata["execution"]}"), {ident}Adapters, {len(metadata["adapters"])} }},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['typed_ops'])};")
    a("inline const FDecl* Find(const FString& Op)")
    a("{")
    a("\tfor (const FDecl& Decl : All) if (Op == Decl.Op) return &Decl;")
    a("\treturn nullptr;")
    a("}")
    a("inline bool IsActive(const FString& Op)")
    a("{")
    a("\treturn Find(Op) != nullptr;")
    a("}")
    a("}")
    a("namespace TypedOpError")
    a("{")
    a("struct FDecl { const TCHAR* Op; const TCHAR* const* Codes; int32 NumCodes; };")
    for op, error_codes in sorted(data["typed_op_errors"].items()):
        ident = "".join(word.capitalize() for word in op.split("_"))
        if error_codes:
            a(f"inline const TCHAR* const {ident}Codes[] = {{")
            for code in error_codes:
                a(f'\tTEXT("{code}"),')
            a("};")
    a("inline const FDecl All[] = {")
    for op, error_codes in sorted(data["typed_op_errors"].items()):
        ident = "".join(word.capitalize() for word in op.split("_"))
        codes = f"{ident}Codes" if error_codes else "nullptr"
        a(f'\t{{TEXT("{op}"), {codes}, {len(error_codes)}}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['typed_op_errors'])};")
    a("inline const FDecl* Find(const FString& Op)")
    a("{")
    a("\tfor (const FDecl& Decl : All) if (Op == Decl.Op) return &Decl;")
    a("\treturn nullptr;")
    a("}")
    a("}")
    a("namespace Limits")
    a("{")
    for name, value in data["connect_limits"].items():
        ident = "".join(word.capitalize() for word in name.split("_"))
        ctype = "double" if isinstance(value, float) else "int64"
        literal = repr(value)
        a(f"inline constexpr {ctype} {ident} = {literal};")
    a("}")
    a("namespace ConfigurableLimit")
    a("{")
    a("struct FDecl { const TCHAR* Name; const TCHAR* Type; };")
    for name, type_name in data["configurable_connect_limits"].items():
        ident = "".join(word.capitalize() for word in name.split("_"))
        a(f'inline const TCHAR* {ident} = TEXT("{name}");')
    a("inline const FDecl All[] = {")
    for name, type_name in data["configurable_connect_limits"].items():
        a(f'\t{{TEXT("{name}"), TEXT("{type_name}")}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['configurable_connect_limits'])};")
    a("}")
    a("")
    a("namespace TypedResult")
    a("{")
    a("struct FField { const TCHAR* Name; const TCHAR* Type; const TCHAR* LengthFrom; const TCHAR* Literal; bool Required; };")
    a("struct FShape { const TCHAR* Name; const FField* Fields; int32 Num; };")
    for shape_name, shape in data["result_shapes"].items():
        ident = "".join(word.capitalize() for word in shape_name.split("_"))
        fields = shape.get("fields") or {}
        if fields:
            a(f"inline const FField {ident}Fields[] = {{")
            for field_name, spec in fields.items():
                length = f'TEXT("{spec["length_from"]}")' if spec.get("length_from") else "nullptr"
                raw_literal = spec.get("value")
                literal_value = str(raw_literal).lower() if isinstance(raw_literal, bool) else raw_literal
                literal = f'TEXT("{literal_value}")' if raw_literal is not None else "nullptr"
                required = "false" if spec.get("optional", False) else "true"
                a(f'\t{{TEXT("{field_name}"), TEXT("{spec["type"]}"), {length}, {literal}, {required}}},')
            a("};")
    a("inline const FShape All[] = {")
    for shape_name, shape in data["result_shapes"].items():
        ident = "".join(word.capitalize() for word in shape_name.split("_"))
        fields = shape.get("fields") or {}
        field_ptr = f"{ident}Fields" if fields else "nullptr"
        a(f'\t{{TEXT("{shape_name}"), {field_ptr}, {len(fields)}}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['result_shapes'])};")
    a("inline const FShape* Find(const FString& Name)")
    a("{")
    a("\tfor (const FShape& Shape : All) if (Name == Shape.Name) return &Shape;")
    a("\treturn nullptr;")
    a("}")
    result_variants = [
        (shape_name, shape["tagged"]["field"], tag, target)
        for shape_name, shape in data["result_shapes"].items()
        if "tagged" in shape
        for tag, target in shape["tagged"]["variants"].items()
    ]
    if result_variants:
        a("struct FTaggedVariant { const TCHAR* Union; const TCHAR* Field; const TCHAR* Tag; const TCHAR* Shape; };")
        a("inline const FTaggedVariant TaggedVariants[] = {")
        for union, field, tag, target in result_variants:
            a(f'\t{{TEXT("{union}"), TEXT("{field}"), TEXT("{tag}"), TEXT("{target}")}},')
        a("};")
        a(f"inline constexpr int32 TaggedVariantCount = {len(result_variants)};")
    a("}")
    a("")
    a("namespace SubscriptionOption")
    a("{")
    for o in data["sub_options"]:
        ident = "".join(w.capitalize() for w in o["name"].split("_"))
        a(f'\tinline const TCHAR* {ident} = TEXT("{o["wire"]}");')
    a("}")
    a("")

    a("// --- command-line flags --------------------------------------------------")
    a("namespace Flag")
    a("{")
    for name in sorted(data["flags"]):
        a(f'\tinline const TCHAR* {name.replace("URLab", "")} = TEXT("{name}");')
    a("}")
    a("")
    a("// Deleted flags. Nothing parses these; they are listed here")
    a("// so a test can assert no launch path emits one.")
    a("namespace DeletedFlag")
    a("{")
    a("\tinline const TCHAR* All[] = {")
    for flag in sorted(data["deleted"]):
        a(f'\t\tTEXT("{flag}"),')
    a("\t};")
    a(f"\tinline constexpr int32 Count = {len(data['deleted'])};")
    a("}")
    a("")

    a("// --- render-bus topics ---------------------------------------------------")
    a("// The naming grammar of the owner -> subscriber bus. Emitted rather than spelled")
    a("// on each side: two spellings of a topic is two buses. URLabRenderBusTopic")
    a("// builds and parses against these; Python has the same pair.")
    topics = data["topics"]
    a("namespace RenderBusTopic")
    a("{")
    a("\t// The always-published transform tier; asking for nothing lands here.")
    a(f'\tinline const TCHAR* Lean = TEXT("{topics.get("lean", "render")}");')
    a("\t// Root of every negotiated topic. NOT under Lean, and Lean not under it:")
    a("\t// ZMQ matches subscriptions by prefix, so nesting would deliver the tier to")
    a("\t// every lean subscriber. The trailing separator on a built topic is load-bearing")
    a("\t// for the same reason -- without it \"m1\" is a prefix of \"m10\".")
    a(f'\tinline const TCHAR* TieredRoot = TEXT("{topics.get("tiered_root", "debug/")}");')
    a(f"\tinline constexpr int32 TieredRootLen = {len(str(topics.get('tiered_root', 'debug/')))};")
    a("}")
    a("")

    a("// --- op declarations -----------------------------------------------------")
    a("// The op registry's ReplyFields / RequiredFields, emitted rather than typed")
    a("// out at each Reg() site. A Reg() site used to carry its own literal list,")
    a("// which is a second hand-written copy of the schema and rotted the moment a")
    a("// handler was rewritten: render_hello went on declaring mjb / xml /")
    a("// broadcasting long after they left the wire. Reg() now looks the op up here.")
    a("//")
    a("// An op the schema does not describe is ABSENT from this table on purpose,")
    a("// keeps the literals at its Reg() site, and is counted by")
    a("// URLab.Wire.OpDeclarationCoverage so the remainder stays visible.")
    a("namespace Decl")
    a("{")
    a("struct FOpFields")
    a("{")
    a("\tconst TCHAR* Op;")
    a("\tconst TCHAR* const* Reply;")
    a("\tint32 ReplyNum;")
    a("\tconst TCHAR* const* Required;")
    a("\tint32 RequiredNum;")
    a("};")
    a("")
    a("namespace Fields")
    a("{")
    for op, decl in sorted(data["op_decls"].items()):
        ident = "".join(w.capitalize() for w in op.split("_"))
        if decl["reply"]:
            inner = ", ".join(f'TEXT("{f}")' for f in decl["reply"])
            a(f"\tinline const TCHAR* const {ident}Reply[] = {{{inner}}};")
        if decl["required"]:
            inner = ", ".join(f'TEXT("{f}")' for f in decl["required"])
            a(f"\tinline const TCHAR* const {ident}Required[] = {{{inner}}};")
    a("}")
    a("")
    a("inline const FOpFields All[] = {")
    for op, decl in sorted(data["op_decls"].items()):
        ident = "".join(w.capitalize() for w in op.split("_"))
        rep = f"Fields::{ident}Reply" if decl["reply"] else "nullptr"
        req = f"Fields::{ident}Required" if decl["required"] else "nullptr"
        a(f'\t{{TEXT("{op}"), {rep}, {len(decl["reply"])}, {req}, {len(decl["required"])}}},')
    a("};")
    a(f"inline constexpr int32 Count = {len(data['op_decls'])};")
    a("")
    a("/** The schema's declaration for an op, or nullptr when the schema does not")
    a(" *  describe it -- in which case the Reg() site's own list stands. */")
    a("inline const FOpFields* Find(const TCHAR* Op)")
    a("{")
    a("\tfor (int32 i = 0; i < Count; ++i)")
    a("\t{")
    a("\t\tif (FCString::Strcmp(All[i].Op, Op) == 0)")
    a("\t\t{")
    a("\t\t\treturn &All[i];")
    a("\t\t}")
    a("\t}")
    a("\treturn nullptr;")
    a("}")
    a("} // namespace Decl")
    a("")

    a("// --- conventions ---------------------------------------------------------")
    conv = data["conventions"]
    a(f'inline const TCHAR* QuaternionOrder = TEXT("{conv.get("quaternion", "wxyz")}");')
    a(f'inline const TCHAR* LengthUnit = TEXT("{(conv.get("units") or {}).get("length", "metre")}");')
    a("")
    a("} // namespace URLabWire")
    a("")
    return "\n".join(L)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the outputs are current; write nothing")
    args = parser.parse_args()

    schema = _load()
    digest = _schema_digest()
    data = collect(schema)

    outputs = [(PY_OUT, emit_python(data, digest)), (CPP_OUT, emit_cpp(data, digest))]

    stale = []
    for path, text in outputs:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")

    if args.check:
        if stale:
            print("STALE generated files (run wire/gen_wire.py):")
            for path in stale:
                print(f"  {path}")
            return 1
        print("generated files are current")
        # The generated files matching the schema proves only half of the loop.
        # The schema can still be a description of a wire the handlers left
        # behind, and it was: `render_hello` kept advertising fields deleted
        # from the wire while every check here stayed green, because nothing
        # compared the schema against the code. That comparison runs here.
        return check_emission.main_check()

    print(f"schema  {SCHEMA.relative_to(PLUGIN)}  sha256 {digest[:16]}...")

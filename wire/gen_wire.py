def _ident(name: str) -> str:
    """A safe upper-case identifier fragment."""
    return "".join(c if c.isalnum() else "_" for c in str(name)).upper()


def _pytuple(items) -> str:
    """Render a Python tuple literal that is valid at any length."""
    items = [i for i in items if i is not None]
    if not items:
        return "()"
    inner = ", ".join(f'"{i}"' for i in items)
    return f"({inner},)" if len(items) == 1 else f"({inner})"


def _load() -> dict:
    return yaml.safe_load(SCHEMA.read_text(encoding="utf-8"))


def _schema_digest() -> str:
    return hashlib.sha256(SCHEMA.read_bytes()).hexdigest()


# --------------------------------------------------------------------------
# collection: pull the vocabulary out of the schema in one place, so both
# emitters below are guaranteed to see identical data.
# --------------------------------------------------------------------------
# Wire-shape names the op registry understands. The schema records the real
# type (`bin`, `map<string, bin>`, `array<string>`); the registry only cares
# about the SHAPE a client stub has to unpack, so several schema types collapse
# onto one name. Binary rides as an object because that is what it looks like
# once the msgpack unpacker has rewritten it into the JSON DOM.
_WIRE_SHAPE = {
    "string": "string",
    "int": "int",
    "float": "float",
    "bool": "bool",
    "object": "object",
    "bin": "object",
    "msgpack": "object",
    "msgpack_bin": "object",
}


def _wire_shape(schema_type) -> str:
    if not isinstance(schema_type, str):
        return "object"
    t = schema_type.strip()
    if t.startswith("array<"):
        return "array"
    if t.startswith("map<"):
        return "object"
    return _WIRE_SHAPE.get(t, "object")


def _resolve_path(msg: dict, where: str):
    """Follow a `reply_fields_at` path such as `reply.fields` into a message."""
    node = msg
    for part in str(where).split("."):
        if not isinstance(node, dict):
            return None
        node = node.get(part)
    return node


def _decl_entries(fields) -> list[tuple[str, str, bool]]:
    """(name, wire shape, optional) per TOP-LEVEL wire key in a field list.

    Skips the entries that are not top-level keys of this message: `location:`
    puts a field inside another object, a `[]` in the name names an array
    element, and `emitted_by:` marks a field some other component writes.
    """
    out: list[tuple[str, str, bool]] = []
    for f in fields or []:
        if not isinstance(f, dict) or f.get("location"):
            continue
        raw = f.get("name")
        shape = _wire_shape(f.get("type"))
        optional = bool(f.get("optional"))
        for n in raw if isinstance(raw, list) else [raw]:
            if isinstance(n, str) and "[" not in n:
                out.append((n, shape, optional))
    return out


def collect_op_declarations(schema: dict) -> dict[str, dict]:
    """op -> {'reply': [...], 'required': [...]} for every op the schema describes.

    This is what replaces the hand-typed `ReplyFields` / `RequiredFields` at each
    Reg() site. `required` comes from `registry_required`, NOT from `required`:
    the first says the dispatcher rejects the request declaratively, the second is
    a protocol statement, and several protocol-required fields are validated
    inside their handler on purpose so the caller gets a specific error instead of
    the generic missing-field envelope.
    """
    out: dict[str, dict] = {}
    for name, msg in (schema.get("messages") or {}).items():
        if not isinstance(msg, dict):
            continue
        op = msg.get("op")
        where = msg.get("reply_fields_at")
        if msg.get("typed_dispatch"):
            continue
        if not op or not where:
            continue
        fields = _resolve_path(msg, where)
        if not isinstance(fields, list):
            continue
        reply = [
            f"{n}:{shape}{'?' if opt else ''}"
            for n, shape, opt in _decl_entries(fields)
        ]
        req_where = msg.get("request_fields_at")
        req_fields = _resolve_path(msg, req_where) if req_where else None
        required: list[str] = []
        for f in req_fields or []:
            if not isinstance(f, dict) or not f.get("registry_required"):
                continue
            raw = f.get("name")
            required.extend(n for n in (raw if isinstance(raw, list) else [raw])
                            if isinstance(n, str))
        out[op] = {"reply": reply, "required": required, "message": name}
    return out


_REQUEST_PRIMITIVES = {
    "string", "nonempty_string", "bool", "finite_float", "nonnegative_int64",
    "int64", "positive_int64", "positive_uint32", "finite_vec3", "binary", "literal",
}
_LENGTH_TYPES = {"nonnegative_int64", "positive_int64", "positive_uint32"}


def _array_element(type_name: str) -> str | None:
    if type_name.startswith("array<") and type_name.endswith(">"):
        return type_name[6:-1]
    return None


def _validate_shapes(shapes: dict, *, request: bool) -> None:
    kind = "request" if request else "result"
    if not isinstance(shapes, dict):
        raise ValueError(f"protocol_v2_{kind}_shapes must be a map")
    references: dict[str, set[str]] = {}
    for shape_name, shape in shapes.items():
        if not isinstance(shape_name, str) or not isinstance(shape, dict):
            raise ValueError(f"every protocol-v2 {kind} shape must be a named map")
        has_fields = "fields" in shape
        has_tagged = "tagged" in shape
        if has_fields == has_tagged or set(shape) - {"fields", "tagged"}:
            raise ValueError(
                f"{kind} shape {shape_name!r} must declare exactly one of fields or tagged"
            )
        references[shape_name] = set()
        if has_tagged:
            tagged = shape["tagged"]
            if not isinstance(tagged, dict) or set(tagged) != {"field", "variants"}:
                raise ValueError(
                    f"{kind} shape {shape_name!r} tagged declaration must contain field and variants"
                )
            discriminator = tagged["field"]
            variants = tagged["variants"]
            if not isinstance(discriminator, str) or not discriminator:
                raise ValueError(
                    f"{kind} shape {shape_name!r} has an invalid tagged discriminator"
                )
            if not isinstance(variants, dict) or not variants:
                raise ValueError(
                    f"{kind} shape {shape_name!r} must declare tagged variants"
                )
            for tag, target_name in variants.items():
                if not isinstance(tag, str) or not tag:
                    raise ValueError(f"{kind} shape {shape_name!r} has an invalid variant tag")
                if not isinstance(target_name, str) or target_name not in shapes:
                    raise ValueError(
                        f"{kind} shape {shape_name!r} variant {tag!r} references "
                        f"unknown shape {target_name!r}"
                    )
                target = shapes[target_name]
                if not isinstance(target, dict) or not isinstance(target.get("fields"), dict):
                    raise ValueError(
                        f"{kind} shape {shape_name!r} variant {tag!r} must reference "
                        "an exact fields shape"
                    )
                discriminator_spec = target["fields"].get(discriminator)
                expected = {"type": "literal", "value": tag}
                if request:
                    expected["required"] = True
                if not isinstance(discriminator_spec, dict) or any(
                    discriminator_spec.get(key) != value for key, value in expected.items()
                ):
                    literal_kind = "required literal" if request else "literal"
                    raise ValueError(
                        f"{kind} shape {shape_name!r} variant {tag!r} must declare "
                        f"{target_name!r}.{discriminator} as its matching {literal_kind}"
                    )
                references[shape_name].add(target_name)
            continue
        fields = shape.get("fields")
        if not isinstance(fields, dict):
            raise ValueError(f"{kind} shape {shape_name!r} must declare a fields map")
        for field_name, spec in fields.items():
            if not isinstance(field_name, str) or not isinstance(spec, dict):
                raise ValueError(f"{kind} shape {shape_name!r} has an invalid field")
            if request and type(spec.get("required")) is not bool:
                raise ValueError(
                    f"request shape {shape_name!r}.{field_name} must explicitly declare required"
                )
            type_name = spec.get("type")
            if not isinstance(type_name, str):
                raise ValueError(f"{kind} shape {shape_name!r}.{field_name} has no type")
            element = _array_element(type_name)
            referenced = element if element is not None else type_name
            if element is not None and _array_element(element) is not None:
                raise ValueError(f"{kind} shape {shape_name!r}.{field_name} has a nested array type")
            if referenced not in _REQUEST_PRIMITIVES:
                if referenced not in shapes:
                    raise ValueError(
                        f"{kind} shape {shape_name!r}.{field_name} references unknown type {referenced!r}"
                    )
                references[shape_name].add(referenced)
            if type_name == "literal":
                if not isinstance(spec.get("value"), str):
                    raise ValueError(
                        f"{kind} shape {shape_name!r}.{field_name} literal must be a string"
                    )
            elif type_name == "bool" and "value" in spec:
                if type(spec["value"]) is not bool:
                    raise ValueError(
                        f"{kind} shape {shape_name!r}.{field_name} boolean literal must be a bool"
                    )
            elif "value" in spec:
                raise ValueError(
                    f"{kind} shape {shape_name!r}.{field_name} has value without literal type"
                )
            length_from = spec.get("length_from")
            if length_from is not None:
                if element is None or not isinstance(length_from, str) or not length_from:
                    raise ValueError(
                        f"{kind} shape {shape_name!r}.{field_name} has invalid length_from"
                    )
                source_shape = shape
                source_spec = None
                components = length_from.split(".")
                for component_index, component in enumerate(components):
                    source_spec = source_shape["fields"].get(component)
                    if not isinstance(source_spec, dict):
                        raise ValueError(
                            f"{kind} shape {shape_name!r}.{field_name} length source "
                            f"{length_from!r} does not exist"
                        )
                    if component_index + 1 < len(components):
                        nested_type = source_spec.get("type")
                        if (
                            nested_type not in shapes
                            or not isinstance(shapes[nested_type].get("fields"), dict)
                        ):
                            raise ValueError(
                                f"{kind} shape {shape_name!r}.{field_name} length source "
                                f"{length_from!r} is not a map path"
                            )
                        source_shape = shapes[nested_type]
                if source_spec.get("type") not in _LENGTH_TYPES:
                    raise ValueError(
                        f"{kind} shape {shape_name!r}.{field_name} length source "
                        f"{length_from!r} is not a nonnegative integer"
                    )

    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(name: str) -> None:
        if name in visiting:
            raise ValueError(f"{kind} shape reference cycle includes {name!r}")
        if name in visited:
            return
        visiting.add(name)
        for child in references[name]:
            visit(child)
        visiting.remove(name)
        visited.add(name)

    for name in shapes:
        visit(name)


def validate_request_shapes(shapes: dict) -> None:
    _validate_shapes(shapes, request=True)


def validate_result_shapes(shapes: dict) -> None:
    _validate_shapes(shapes, request=False)


def collect(schema: dict) -> dict:
    messages = schema.get("messages") or {}

    ops: dict[str, str] = {}
    keys: dict[str, list[str]] = {}
    for name, message in messages.items():
        if not isinstance(message, dict) or message.get("generated") is False:
            continue
        op = message.get("op")
        if op:
            ops[name] = op
        field_names: list[str] = []
        for field in message.get("fields") or []:
            if not isinstance(field, dict):
                continue
            raw = field.get("name")
            # a few fields are written as a list, e.g. [ucpos, ucfwd, ucup]
            field_names.extend(raw if isinstance(raw, list) else [raw])
        if field_names:
            keys[name] = [f for f in field_names if isinstance(f, str)]

    enums: dict[str, list[str]] = {}
    for name, body in (schema.get("enums") or {}).items():
        values = body.get("values") if isinstance(body, dict) else None
        if not values:
            continue
        tokens = [v.get("wire") for v in values if isinstance(v, dict) and v.get("wire")]
        if tokens:
            enums[name] = tokens

    flags: dict[str, dict] = {}
    for name, body in (schema.get("cli_flags") or {}).items():
        if not isinstance(body, dict):
            continue
        entry: dict = {"kind": body.get("kind")}
        if body.get("tokens"):
            entry["tokens"] = list(body["tokens"])
        if body.get("keys"):
            entry["keys"] = [k["key"] for k in body["keys"] if isinstance(k, dict)]
        # some flags spell their allowed values as `values:` (list of dicts with
        # a `token`) or defer to an enum via `values_from_enum:`
        if body.get("values"):
            entry["tokens"] = entry.get("tokens", []) + [
                v["token"] for v in body["values"]
                if isinstance(v, dict) and v.get("token")
            ]
        if body.get("values_from_enum"):
            entry["from_enum"] = body["values_from_enum"]
        flags[name] = entry

    deleted = [
        f["flag"]
        for f in ((schema.get("cli_flags_deleted") or {}).get("flags") or [])
        if isinstance(f, dict) and f.get("flag")
    ]

    # The one capability vocabulary, split by the direction each points.
    # `caps` keeps schema order because the C++ enum indexes into it.
    cap_model: dict[str, list] = {}
    caps: list[dict] = []
    model = schema.get("capability_model") or {}
    for entry in model.get("capabilities") or []:
        if not isinstance(entry, dict) or not entry.get("name"):
            continue
        if entry.get("kind") == "permission":
            name = entry["name"]
            if entry.get("cli") != name or entry.get("wire") != name:
                raise ValueError(
                    f"permission capability {name!r} must use its canonical name "
                    "for both CLI and wire tokens"
                )
        cap_model.setdefault(entry.get("kind", "unknown"), []).append(entry)
        caps.append(entry)

    # Which permission each op requires. Absent = the declared default, `none`.
    op_perms = dict(((model.get("op_permissions") or {}).get("ops") or {}))
    op_adapters: dict[str, list[str]] = {}
	# Active strict-envelope operations are deliberately separate from the
	# historical inventory: only these are callable on the production byte path.
    request_shapes = schema.get("protocol_v2_request_shapes") or {}
    validate_request_shapes(request_shapes)
    result_shapes = schema.get("protocol_v2_result_shapes") or {}
    validate_result_shapes(result_shapes)
    typed_ops: dict[str, dict] = {}
    typed_op_errors: dict[str, tuple[str, ...]] = {}
    for message in messages.values():
        if not isinstance(message, dict) or not message.get("op"):
            continue
        supported = [name for name, face in (message.get("faces") or {}).items()
                     if isinstance(face, dict) and face.get("status") == "supported"]
        if supported:
            op_adapters[message["op"]] = supported
        if message.get("typed_dispatch") == "active":
            required_metadata = (
                "request_shape", "service", "permission", "authority", "execution", "adapters"
            )
            missing = [key for key in required_metadata if key not in message]
            if missing:
                raise ValueError(
                    f"active typed op {message['op']!r} lacks explicit metadata: {', '.join(missing)}"
                )
            shape_name = message["request_shape"]
            if shape_name not in request_shapes:
                raise ValueError(
                    f"active typed op {message['op']!r} references unknown request shape {shape_name!r}"
                )
            if message["op"] not in result_shapes:
                raise ValueError(
                    f"active typed op {message['op']!r} has no exact result shape"
                )
            adapters = message["adapters"]
            if not isinstance(adapters, list) or not adapters or adapters != supported:
                raise ValueError(
                    f"active typed op {message['op']!r} adapters must exactly match supported faces"
                )
            if message["service"] not in (schema.get("protocol_v2_services") or []):
                raise ValueError(f"active typed op {message['op']!r} names an unknown service")
            permission_names = {
                entry["name"] for entry in caps if entry.get("kind") == "permission"
            }
            if message["permission"] != "none" and message["permission"] not in permission_names:
                raise ValueError(f"active typed op {message['op']!r} names an unknown permission")
            for key in ("authority", "execution"):
                if not isinstance(message[key], str) or not message[key]:
                    raise ValueError(
                        f"active typed op {message['op']!r} has invalid {key} metadata"
                    )
            declared_shape = request_shapes[shape_name]
            if "fields" in declared_shape:
                declared_fields = declared_shape["fields"]
            else:
                variants = declared_shape["tagged"]["variants"]
                variant_fields = [
                    request_shapes[target]["fields"] for target in variants.values()
                ]
                # A tagged exact map may have fields that exist only in one
                # variant. The human-facing request_fields inventory describes
                # those as optional at the union level; the generated recursive
                # validator still enforces them as required in that exact branch.
                declared_fields = {}
                declared_names = set().union(*(set(fields) for fields in variant_fields))
                for name in declared_names:
                    specs = [fields[name] for fields in variant_fields if name in fields]
                    type_names = {spec["type"] for spec in specs}
                    if len(type_names) != 1:
                        raise ValueError(
                            f"active typed op {message['op']!r} tagged field {name!r} "
                            "disagrees on type"
                        )
                    declared_fields[name] = {
                        "type": specs[0]["type"],
                        "required": len(specs) == len(variant_fields)
                            and all(spec["required"] for spec in specs),
                    }
            message_fields = {
                field["name"]: (field["type"], bool(field.get("required")))
                for field in (message.get("request_fields") or [])
            }
            shape_fields = {
                name: (spec["type"], spec["required"])
                for name, spec in declared_fields.items()
            }
            if message_fields != shape_fields:
                raise ValueError(
                    f"active typed op {message['op']!r} request_fields disagree with {shape_name!r}"
                )
            typed_ops[message["op"]] = {
                key: message[key] for key in required_metadata
            }
            error_codes = tuple(
                entry.get("code")
                for entry in (message.get("errors") or [])
                if isinstance(entry, dict)
            )
            if any(not isinstance(code, str) or not code for code in error_codes):
                raise ValueError(
                    f"active typed op {message['op']!r} has an invalid error declaration"
                )
            if len(error_codes) != len(set(error_codes)):
                raise ValueError(
                    f"active typed op {message['op']!r} declares a duplicate error code"
                )
            typed_op_errors[message["op"]] = error_codes
    sub_options = [
        o for o in ((model.get("subscription_options") or {}).get("options") or [])
        if isinstance(o, dict) and o.get("name")
    ]

    configurable_limits = schema.get("protocol_v2_configurable_limits") or {}
    if not isinstance(configurable_limits, dict) or any(
        not isinstance(name, str)
        or not name
        or type_name not in {"positive_int64", "finite_float"}
        for name, type_name in configurable_limits.items()
    ):
        raise ValueError(
            "protocol_v2_configurable_limits must map names to supported primitive types"
        )
    fixed_limits = schema.get("protocol_v2_limits") or {}
    if set(configurable_limits) & set(fixed_limits):
        raise ValueError("fixed and configurable protocol-v2 limits overlap")

    return {
        "topics": schema.get("render_bus_topics") or {},
        "op_decls": collect_op_declarations(schema),
        "cap_model": cap_model,
        "caps": caps,
        "op_perms": op_perms,
        "op_adapters": op_adapters,
        "request_shapes": request_shapes,
        "typed_ops": typed_ops,
        "typed_op_errors": typed_op_errors,
        "connect_limits": fixed_limits,
        "configurable_connect_limits": configurable_limits,
        "typed_services": schema.get("protocol_v2_services") or [],
        "command_adapters": schema.get("protocol_v2_command_adapters") or [],
        "result_shapes": result_shapes,
        "sub_options": sub_options,
        "ops": ops,
        "keys": keys,
        "enums": enums,
        "flags": flags,
        "deleted": deleted,
        "conventions": schema.get("conventions") or {},
    }



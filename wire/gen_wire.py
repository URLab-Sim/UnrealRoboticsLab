def emit_python(data: dict, digest: str) -> str:
    L: list[str] = []
    a = L.append
    a('"""' + BANNER)
    a("")
    a("The shared vocabulary of the UE <-> Python wire: op names, message keys,")
    a("enum tokens, the six capability vocabularies, and the command-line surface.")
    a("")
    a("Import these instead of typing string literals. A literal is how the farm")
    a("launcher kept emitting three flags the plugin had deleted.")
    a('"""')
    a("from __future__ import annotations")
    a("")
    a(f'SCHEMA_SHA256 = "{digest}"')
    a("")

    a("# --- ops ------------------------------------------------------------------")
    for name, op in sorted(data["ops"].items()):
        a(f'OP_{_ident(name)} = "{op}"')
    a("")
    a("ALL_OPS = frozenset({")
    for name in sorted(data["ops"]):
        a(f"    OP_{_ident(name)},")
    a("})")
    a("")

    a("# --- message keys ---------------------------------------------------------")
    a("KEYS: dict[str, tuple[str, ...]] = {")
    for name, fields in sorted(data["keys"].items()):
        a(f'    "{name}": {_pytuple(fields)},')
    a("}")
    a("")

    a("# --- enums ----------------------------------------------------------------")
    for name, tokens in sorted(data["enums"].items()):
        a(f"{_ident(name)}_VALUES = {_pytuple(tokens)}")
    a("")

    a("# --- capability model, split by kind ---------------------------------------")
    a("# service = an ingress you stand up; output = data you emit; permission =")
    a("# authority you grant peers; local = a convenience with no wire at all.")
    a("# Kept apart because the direction each points is what makes them different.")
    a("CAPABILITY_NAMES = " + _pytuple([e["name"] for e in data["caps"]]))
    a("")
    a("CAPABILITIES_BY_KIND: dict[str, tuple[str, ...]] = {")
    for kind, entries in sorted(data["cap_model"].items()):
        names = [e["name"] for e in entries]
        a(f'    "{kind}": {_pytuple(names)},')
    a("}")
    a("")
    permission_names = [e["name"] for e in data["cap_model"].get("permission", [])]
    a("# Exact permission vocabulary accepted by a protocol-v2 bootstrap.")
    a("# Generated from permission capability names, not wire aliases or callers.")
    a("PROTOCOL_V2_PERMISSION_TOKENS = frozenset(" + repr(tuple(permission_names)) + ")")
    a("")
    a("# The wire token for each capability that has one. A `local` capability has")
    a("# none by definition: it is never advertised and cannot be asked for.")
    a("CAPABILITY_WIRE_TOKENS: dict[str, str] = {")
    for e in data["caps"]:
        if e.get("wire"):
            a(f'    "{e["name"]}": "{e["wire"]}",')
    a("}")
    a("")
    a("# The -URLabCaps token for each capability. The token IS the name; the map")
    a("# exists so a caller can assert that rather than assume it.")
    a("CAPABILITY_CLI_TOKENS: dict[str, str] = {")
    for e in data["caps"]:
        if e.get("cli"):
            a(f'    "{e["name"]}": "{e["cli"]}",')
    a("}")
    a("")
    a("# The permission each op requires before the dispatcher will run it.")
    a("# An op absent from this table requires none: that is the declared default,")
    a("# not an omission.")
    a("OP_PERMISSIONS: dict[str, str] = {")
    for op, perm in sorted(data["op_perms"].items()):
        a(f'    "{op}": "{perm}",')
    a("}")
    a("")
    a("OP_ALLOWED_ADAPTERS: dict[str, tuple[str, ...]] = {")
    for op, adapters in sorted(data["op_adapters"].items()):
        a(f'    "{op}": {_pytuple(adapters)},')
    a("}")
    a("")
    a("ACTIVE_TYPED_OPS = frozenset({")
    for op in sorted(data["typed_ops"]):
        a(f'    "{op}",')
    a("})")
    a(f"TYPED_REQUEST_SHAPES = {data['request_shapes']!r}")
    a(f"TYPED_OP_METADATA = {data['typed_ops']!r}")
    a(f"TYPED_OP_ERRORS = {data['typed_op_errors']!r}")
    a(f"CONNECT_LIMITS = {data['connect_limits']!r}")
    a(f"CONFIGURABLE_CONNECT_LIMITS = {data['configurable_connect_limits']!r}")
    a(f"ACTIVE_TYPED_SERVICES = {_pytuple(data['typed_services'])}")
    a(f"COMMAND_ADAPTERS = {_pytuple(data['command_adapters'])}")
    a(f"TYPED_RESULT_SHAPES = {data['result_shapes']!r}")
    a("")
    a("# Negotiated per subscription and released on disconnect, so their lifetime")
    a("# is the subscription's rather than the instance's.")
    a(f"SUBSCRIPTION_OPTIONS = {_pytuple([o['name'] for o in data['sub_options']])}")
    a("")

    a("# --- command-line surface -------------------------------------------------")
    for name, body in sorted(data["flags"].items()):
        a(f'FLAG_{_ident(name)} = "{name}"')
    a("")
    a("FLAG_TOKENS: dict[str, tuple[str, ...]] = {")
    for name, body in sorted(data["flags"].items()):
        toks = body.get("tokens") or body.get("keys") or []
        a(f'    "{name}": {_pytuple(toks)},')
    a("}")
    a("")
    a("# Flags whose allowed values come from an enum rather than a token list.")
    a("FLAG_VALUES_FROM_ENUM: dict[str, str] = {")
    for name, body in sorted(data["flags"].items()):
        if body.get("from_enum"):
            a(f'    "{name}": "{body["from_enum"]}",')
    a("}")
    a("")
    a("# Deleted flags. They parse as nothing, so emitting one silently produces")
    a("# a server that never serves. Asserted against by the tests.")
    a("DELETED_FLAGS = frozenset({")
    for flag in sorted(data["deleted"]):
        a(f'    "{flag}",')
    a("})")
    a("")

    a("# --- render-bus topics ----------------------------------------------------")
    a("# The subscription IS the request on a publish/subscribe bus, so the topic")
    a("# name carries the capabilities. Two rules are load-bearing and neither is")
    a("# guessable: the tiered topics are NOT nested under the lean one, because ZMQ")
    a("# matches by prefix and a lean subscriber would receive the tier; and the")
    a("# trailing separator exists so that `m1` does not prefix-match `m10`.")
    topics = data["topics"]
    a(f'RENDER_BUS_TOPIC_LEAN = "{topics.get("lean", "render")}"')
    a(f'RENDER_BUS_TOPIC_TIERED_ROOT = "{topics.get("tiered_root", "debug/")}"')
    a("")
    a("")
    a("def render_bus_topic(contacts: bool, overlay: bool, maxcontacts: int) -> str:")
    a('    """The topic a subscriber attaches to in order to ask for these caps.')
    a("")
    a("    Asking for nothing is the lean tier, so a lean subscriber needs no special")
    a("    case. The cap is pinned to 0 when contacts are off, which keeps the topic")
    a("    canonical for a capability set: two subscribers wanting the same thing land")
    a("    on the same topic and the owner builds that frame once.")
    a('    """')
    a("    if not contacts and not overlay:")
    a("        return RENDER_BUS_TOPIC_LEAN")
    a("    cap = max(0, int(maxcontacts)) if contacts else 0")
    a("    return (f\"{RENDER_BUS_TOPIC_TIERED_ROOT}c{int(bool(contacts))}\"")
    a("            f\"o{int(bool(overlay))}m{cap}/\")")
    a("")

    a("# --- op declarations ------------------------------------------------------")
    a("# What each op's *_ok reply carries and which request fields the dispatcher")
    a("# rejects a request for missing. These ARE the C++ op registry's ReplyFields")
    a("# and RequiredFields -- both sides read the same emission -- so the `meta` op")
    a("# a server ships can be checked against them rather than believed.")
    a("OP_REPLY_FIELDS: dict[str, tuple[str, ...]] = {")
    for op, decl in sorted(data["op_decls"].items()):
        a(f'    "{op}": {_pytuple(decl["reply"])},')
    a("}")
    a("")
    a("OP_REQUIRED_FIELDS: dict[str, tuple[str, ...]] = {")
    for op, decl in sorted(data["op_decls"].items()):
        a(f'    "{op}": {_pytuple(decl["required"])},')
    a("}")
    a("")

    a("# --- conventions ----------------------------------------------------------")
    conv = data["conventions"]
    a(f'QUATERNION_ORDER = "{conv.get("quaternion", "wxyz")}"')
    a(f'LENGTH_UNIT = "{(conv.get("units") or {}).get("length", "metre")}"')
    a(f'SERIALISATION = "{conv.get("serialisation", "msgpack")}"')
    a("")
    return "\n".join(L)



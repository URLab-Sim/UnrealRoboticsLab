"""Generate the shared vocabulary from `urlab_wire.yaml`.

Both repos used to keep their own hand-typed copies of the op names, message
keys, enum tokens, topic spellings and command-line flags — seven copies, none
compared. This emits them from the schema instead, so a rename lands on both
sides or fails loudly.

Outputs (both overwritten in place, both marked do-not-edit):

    URLab_Bridge/src/urlab_client/_wire/generated.py
    UnrealRoboticsLab/Source/URLab/Public/Wire/UrlabWire.gen.h

What is emitted: the vocabulary (ops, keys, enums, capabilities, flags), the
render-bus topic grammar, op registry fields, and recursive protocol-v2 request
and result shapes shared by C++ and Python.

`--check` proves the generated files match the schema AND that the schema still
matches the handlers. Only the second half would have caught `render_hello`
being rewritten out from under its own description.

    ./wire/gen_wire.py            # write both outputs
    ./wire/gen_wire.py --check    # exit 1 if either is stale, or if the schema
                                  # no longer matches the handlers (for CI)
"""
